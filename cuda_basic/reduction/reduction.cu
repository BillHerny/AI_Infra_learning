------------------------------------------------------------------------
3.1 命令行参数
------------------------------------------------------------------------
    int n         = (argc > 1) ? atoi(argv[1]) : (1 << 26);
    int blockSize = (argc > 2) ? atoi(argv[2]) : 256;

    结构与 vector_add 完全相同，只是变量名从 thread_per_block
    简化成了 blockSize。

        命令                              argc   n          blockSize   grid
        -------------------------------   ----   --------   ---------   ------
        ./reduction                       1      67108864   256         262144
        ./reduction 1024                  2      1024       256         4
        ./reduction 1024 512              3      1024       512         2

    ⚠ blockSize 必须同时满足三个条件：
        · 是 32 的整数倍（对齐 warp）—— 否则最后一个 warp 半空
        · <= 1024（硬件上限）        —— 否则启动失败
        · >= 64（本 kernel 的隐藏约束，见 2.6(4)）

------------------------------------------------------------------------
3.2 算规模与 grid
------------------------------------------------------------------------
    size_t bytes = (size_t)n * sizeof(float);
    int    grid  = (n + blockSize - 1) / blockSize;

    bytes：先转大类型再乘，防 int 溢出（与 vector_add 同）。
    grid ：向上取整除法：先加 (blockSize-1) 再整除。

    ⚠ 规模差异：vector_add 用 grid-stride 循环，grid 大小与 N 解耦；
      本 kernel 是「一线程一元素」，grid 必须精确覆盖：

        vector_add 的 grid 可以只开 24*32 = 768 个 block，靠循环覆盖全部 N
        本 kernel 的 grid = ceil(n / blockSize) = 262144

      为什么不用 grid-stride？因为共享内存归约要求
      「每个 block 恰好装一份完整的数据」。用 grid-stride 的话
      一个 block 会处理多个不连续的片段，树形结构就对不上了。

    ⚠ 隐藏风险：grid 最大是 2^31-1 = 2147483647。本例 262144 很安全。
      N 超过 5497 亿时 grid 才会溢出 → kernel 启动失败
      （由 cudaGetLastError() 抓到）。

------------------------------------------------------------------------
3.3 填充数据与参考值
------------------------------------------------------------------------
    float* h_a = (float*)malloc(bytes);
    for (int i = 0; i < n; i++) h_a[i] = 1.0f;

    double ref = 0.0;
    for (int i = 0; i < n; i++) ref += h_a[i];

    (1) 为什么全填 1.0f
        这样「正确答案」就是 n，肉眼一查便知。
        （与 vector_add 里填 1.0 / 2.0、答案全 3.0 是同一个思路。）

    (2) ref 为什么用 double 累加 —— 藏着一个非常重要的浮点知识点

        如果 ref 也用 float 累加会怎样？

            累加到 16,777,216（= 2^24）时，再加 1.0f：
            2^24 附近 float 的「最小间隔（ulp）」是 2
            → 16777216 + 1 = 16777217 落在两个可表示值正中间
            → 就近舍偶 → 又回到 16777216
            → 之后再怎么加 1.0f 都纹丝不动

            最终得到 16,777,216，而不是 67,108,864 —— 差了整整 4 倍！💥

        ⚠ 结论：float 的有效精度只有约 7 位十进制数字，
          累加超过 2^24 之后就再也分辨不出「加 1」。

    (3) 那 kernel 里的 float 累加为什么不会出错？
        因为 GPU 用的是「树形归约」，不是串行累加：

            串行累加（错误）： ((((1+1)+1)+1)+... 累加器单调增大 → 撞精度墙 💥
            树形归约（正确）： 相邻两数两两相加，所有中间结果都很小

                每对 1+1 = 2      （精确）
                2+2 = 4           （精确）
                4+4 = 8           （精确）
                ...
                全是 2 的幂 → 在 float 里精确可表示！

        本示例逐阶段核对：

            阶段                         数值大小            能否精确
            --------------------------   -----------------   ----------
            block 内每个线程初值          1                   ✅
            block 内树形归约每一步        2,4,8,...,256       ✅ 全是 2 的幂
            每个 block 的部分和           256（= 2^8）        ✅
            主机端 double 累加 262144 个  到 67108864         ✅ double 精确

        所以本示例的结果是完全精确、零误差的。
        这也是第 110 行能用 1e-3 这种「几乎等于要求相等」的容差的原因。

        ⚠ 这不代表 reduction 永远精确。若数组是任意浮点数，
          树形归约也有舍入误差 —— 只是它把误差从 O(n) 降到 O(log n)。
          这是树形归约在数值上的第二个好处，不只是速度。

------------------------------------------------------------------------
3.4 显存分配
------------------------------------------------------------------------
    float *d_a, *d_out;
    CUDA_CHECK(cudaMalloc(&d_a, bytes));
    CUDA_CHECK(cudaMalloc(&d_out, (size_t)grid * sizeof(float)));
    CUDA_CHECK(cudaMemcpy(d_a, h_a, bytes, cudaMemcpyHostToDevice));

    (1) float *d_a, *d_out; 的星号不能省。
        写成 float *d_a, d_out; 的话 d_out 会变成普通 float 变量，
        cudaMalloc(&d_out, ...) 就把显存地址写进一个 4 字节 float → 崩溃。

    (2) d_out 的大小不是 bytes，而是 grid * sizeof(float)：

            d_a   : n 个 float    = 256 MiB   （输入全量）
            d_out : grid 个 float = 1 MiB     （只有 262144 个部分和）

        ⚠ 这是 reduction 与 vector_add 在内存布局上最大的差异：
          vector_add 三个数组等大；reduction 的输出缩小了 blockSize 倍。

    (3) 只拷 d_a，不拷 d_out。
        因为 d_out 是输出，每个位置都会被 kernel 覆盖，不需要初值。

------------------------------------------------------------------------
3.5 算共享内存大小
------------------------------------------------------------------------
    size_t shmem = (size_t)blockSize * sizeof(float);

        blockSize = 256  →  shmem = 256 * 4 = 1024 字节 = 1 KiB

    这个值就是 <<<grid, blockSize, shmem>>> 里的第三个参数。

    为什么共享内存大小值得关注？因为它直接决定一个 SM 上能同时
    驻留几个 block（进而决定占用率）：

        项目                          本机（RTX 4060 Laptop, sm_89）
        ---------------------------   -----------------------------
        每 SM 共享内存总量            ~100 KiB
        每个 block 需要                1 KiB
        → 共享内存允许的 block 数     96+（根本不是瓶颈）
        每 SM 最大 block 数            24
        每 SM 最大 warp 数             48（= 1536 线程）
        每 block（256 线程 = 8 warp）  → 48/8 = 6 个 block 就占满 warp

    结论：1 KiB/block 太小了，共享内存不是占用率的限制因素，
    真正的限制是「每 SM 最多 48 个 warp」。
    所以把 blockSize 从 256 改到 512 / 1024，对占用率没有负面影响。

    对比：若某 kernel 每 block 要 48 KiB 共享内存，
    一个 SM 只能放 2 个 block —— 那才会严重限制占用率。


