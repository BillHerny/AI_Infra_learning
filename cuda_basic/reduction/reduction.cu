------------------------------------------------------------------------
4.1 warm-up
------------------------------------------------------------------------
    reduceSum<<<grid, blockSize, shmem>>>(d_a, d_out, n);
    CUDA_CHECK(cudaGetLastError());
    CUDA_CHECK(cudaDeviceSynchronize());

    这里 cudaGetLastError() 的作用被放大了，因为
    「共享内存相关的启动失败，全都只在运行时才暴露」：

        错误                              后果
        -------------------------------   ----------------------------
        忘了第三个参数 → shmem = 0        sdata 长度 0，写入即越界
        shmem 算小了（比如只给 blockSize）越界
        shmem 超了每 block 上限           启动失败，kernel 根本不跑
        blockSize < 64                    sdata[tid+32] 越界

    这些错误编译期一个都不报。所以这一行不是走过场，
    它是你唯一能提前发现问题的机会。

    cudaDeviceSynchronize() 的双重作用：
      ① 确保 warm-up 真的跑完 → GPU 提频、指令缓存预热；
      ② 把 warm-up 里可能出现的越界/非法访问「逼出来」
         （异步执行下，错误可能很久之后才被 CPU 感知）。

------------------------------------------------------------------------
4.2 <<<grid, blockSize, shmem>>> 三位参数
------------------------------------------------------------------------
    与 vector_add 的 <<<grid, block>>> 相比，多了第三个参数：

            ┌── 第 1 个：grid，开多少个 block
            │      ┌── 第 2 个：blockSize，每个 block 多少线程
            │      │      ┌── 第 3 个：shmem，动态共享内存字节数  ← 新增
            ↓      ↓      ↓
    <<<grid, blockSize, shmem>>>

    完整语法其实有 4 个参数，第 4 个是流（stream）：

        kernel<<<gridDim, blockDim, sharedMemBytes, stream>>>(args...);

    本文件省略了流（等价于默认流 0，同步流）。

    ⚠ 单位：第 3 个参数是「字节数」，不是 float 个数。
      所以必须 blockSize * sizeof(float)，写成 blockSize 就只给了 1/4 空间。

------------------------------------------------------------------------
4.3 best-of-20 计时
------------------------------------------------------------------------
    const int iters = 20;
    float best = 1e30f;
    for (int k = 0; k < iters; k++)
    {
        CUDA_CHECK(cudaEventRecord(start));
        reduceSum<<<grid, blockSize, shmem>>>(d_a, d_out, n);
        CUDA_CHECK(cudaEventRecord(stop));
        CUDA_CHECK(cudaEventSynchronize(stop));

        float ms = 0.0f;
        CUDA_CHECK(cudaEventElapsedTime(&ms, start, stop));
        if (ms < best) best = ms;
    }

    与 vector_add.cu 的计时框架逐字符同构，四步口诀不变：

        create → record(start) → 跑 kernel → record(stop)
               → synchronize(stop) → elapsedTime → destroy

    (1) cudaEventSynchronize(stop) 不能省。
        kernel 是异步的，不等 stop 事件真正到达就读 elapsedTime，
        会读到 0 或上一次的旧值。

    (2) 为什么取最小值而不是平均值。
        GPU 会因温度升高降频，降频只会让时间变长，不会变短。
        所以「最快那一次」最接近硬件上限。
        （你之前在 vector_add 上看到 228 → 245 GB/s 的 13% 波动，
          就是纯粹的温度/频率噪声，不是代码变快。）

    (3) 这里只测 kernel，不含 cudaMemcpy。因为要回答的问题是
        「这个归约算法本身快不快」。

------------------------------------------------------------------------
4.4 本 kernel 的带宽怎么算（与 vector_add 的差异点）
------------------------------------------------------------------------
    printf("bandwidth = %.1f GB/s\n", (bytes / 1e9) / (best / 1e3));
                                     └────────┬────────┘
                                        流量 / 时间

    对比 vector_add.cu 的：

        double gb = 3.0 * bytes / 1e9;      ← 乘了 3

            项目          流量          为什么
            -----------   -----------   ----------------------------------
            vector_add    3 * bytes     读 a(1) + 读 b(1) + 写 c(1)
            本 reduction  1 * bytes     只读 n 个 float；
                                      写 out 只有 grid 个 float
                                      = 1 MiB，占 256 MiB 的 0.4%，可忽略

    ⚠ 这是最容易算错的地方：顺手把 3.0 * 抄过来，
      算出的带宽会虚高 3 倍，直接「超过硬件峰值」。

    判读方法（除以 RTX 4060 Laptop 峰值 256.3 GB/s）：

        得到 180~240 GB/s  → 占峰值 70%~94% → 健康
        得到 > 260 GB/s    → 先怀疑代码，不是机器牛（大概率流量算错了）

    红字记住：超过硬件峰值的数字 = 代码 bug。

    （本机硬件基准：RTX 4060 Laptop，24 SM，
      显存 8 GB GDDR6 128-bit @ 8.01 GHz，峰值带宽约 256.3 GB/s，
      FP32 峰值约 9.5 TFLOP/s，L2 约 24 MiB，PCIe 4.0 x8。）


