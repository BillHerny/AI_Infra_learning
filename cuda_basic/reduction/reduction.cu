========================================================================
第 0 章　全景：reduction 与 vector_add 的本质区别
========================================================================

------------------------------------------------------------------------
0.1 一句话对比
------------------------------------------------------------------------
                     vector_add                  reduction
    每个线程的产出    一个输出元素 c[i]            一个「部分和」
    线程之间          互不打扰                    必须汇合
    输出规模          N 个                        1 个
    额外机制          无                          共享内存 / 栅栏 / warp 协作

    vector_add 是「尴尬并行（embarrassingly parallel）」的极致：
    把 N 份活切成 N 份，谁也不用管谁。

    reduction 不一样：N 个输入最后只剩 1 个输出，
    所以线程之间必须发生「通信」。

        vector_add:   a[i] ─┐
                             ├─ 线程 i ─→ c[i]      各写各的，零协作
                      b[i] ─┘

        reduction:    a[0] ─┐
                      a[1] ─┤
                      a[2] ─┼─ 分层合并（树形）─→ 1 个数   必须协作
                       ... ─┤
                    a[N-1] ─┘

------------------------------------------------------------------------
0.2 归约为什么必须「分层」
------------------------------------------------------------------------
    一个 block 有 256 个线程，各手里一个数，要合并成 1 个。三种做法：

      ① 串行：只让 0 号线程干
         它一个接一个加 256 次 —— 耗时 O(n)
         另外 255 个线程全部空转，白拿工资 ❌

      ② 两两配对劈叉（树形）—— 本文件用的方案
         T0+T128, T1+T129, ... → 128 个数
         T0+T64,  T1+T65,  ... →  64 个数
         ...                   →   1 个数
         每轮把所有线程都用上，只需 log2(256) = 8 轮 ✅

      ③ 原子加法：每个线程 atomicAdd 到同一个地址
         结果正确，但 256 个线程抢同一个地址 → 硬件串行化 ❌

    树形归约的深度是 log2(256) = 8，而不是 256。
    这才是 GPU 该干的事：把 O(n) 变成 O(log n)，
    且每一层的 128 / 64 / 32 个加法是「并行」做的。

------------------------------------------------------------------------
0.3 树形归约可视化（blockSize = 256）
------------------------------------------------------------------------
    下标    0    1    2    3   ...  127  128  129  ...  255
    初始   ┌──┐ ┌──┐ ┌──┐ ┌──┐      ┌──┐ ┌──┐ ┌──┐     ┌──┐
           │1 │ │1 │ │1 │ │1 │      │1 │ │1 │ │1 │     │1 │
           └┬─┘ └┬─┘ └┬─┘ └┬─┘      └┬─┘ └┬─┘ └┬─┘     └┬─┘
    s=128   └────┴────┴────┴─────────┘    ↑            │
            T0..T127 干活，把 [128..255] 加到 [0..127]  │
                                                         ↓ 丢弃
           ┌──┐ ┌──┐ ┌──┐ ┌──┐      ┌───┐
           │2 │ │2 │ │2 │ │2 │      │2  │      ← 128 个数
           └┬─┘ └┬─┘ └┬─┘ └┬─┘      └─┬─┘
    s=64    └────┴────┴────┴──────────┘
           ...                                        ←  64 个数
    ─── 到这里只剩 64 个数，进入「最后一个 warp」阶段 ───
    s=32    [0..31] += [32..63]                      ←  32 个数
    s=16    [0..15] += [16..31]
    ...
    s=1     [0]     += [1]                           ←   1 个数

    一句话：每一步都把「存活的数字个数」减半，8 步之后 256 → 1。


========================================================================
第 1 章　概念预习（8 条新概念）
========================================================================

------------------------------------------------------------------------
1.1 归约（reduction）
------------------------------------------------------------------------
    把 N 个数合并成 1 个数。求和只是其中一种，同一套骨架还适用于：

        求和 sum          单位元 0        合并运算 a + b
        求最大值 max      单位元 -FLT_MAX  合并运算 fmaxf(a, b)
        求最小值 min      单位元 +FLT_MAX  合并运算 fminf(a, b)
        求乘积 product    单位元 1        合并运算 a * b
        点积 dot          单位元 0        合并运算 a * b 后再加
        范数 norm²        单位元 0        合并运算 a * a 后再加

    ⚠ 「单位元」是本章最该记住的词，后面 2.4 会用到。

------------------------------------------------------------------------
1.2 为什么不能「直接加别人寄存器里的数」
------------------------------------------------------------------------
    每个线程的寄存器是「私有」的 —— T0 看不到 T1 的寄存器。
    所以线程之间要交换数据，只有三条路：

        通路                            速度          本文件是否使用
        ----------------------------    -----------   --------------
        共享内存 shared memory          很快（片上）  ✅ 主循环用它
        warp shuffle（__shfl_down_sync）最快（寄存器）✅ 最后一个 warp 用它
        全局内存 / 原子操作             慢（走 L2）   ❌

    上面的代码里 sdata 就是一块「block 内所有线程都能读写」的公共白板。

------------------------------------------------------------------------
1.3 共享内存（shared memory）
------------------------------------------------------------------------
    CUDA 的存储层次：

        速度            容量        谁能访问
        ------------    --------    ----------------------------------
        寄存器          最快 最少    只有本线程（私有）
          ↓
        共享内存        很快 每 block block 内所有线程共享  ← sdata 在这
          ↓                                  （block 之间互不可见！）
        L1 / L2         中    中      GPU 全局
          ↓
        全局内存        慢    最大    所有线程 + cudaMemcpy

    ⚠ 关键：__shared__ 修饰的变量，每个 block 各有一份独立副本：

        block 0 的 sdata[0]  ≠  block 1 的 sdata[0]

        ┌──────── block 0 ────────┐  ┌──────── block 1 ────────┐
        │ sdata[0..255]（1 KiB）   │  │ sdata[0..255]（1 KiB）   │
        └─────────────────────────┘  └─────────────────────────┘

    所以两个 block 之间无法通过共享内存交换数据 —— 这是硬性限制。
    跨 block 只能靠全局内存（本文件靠 out[blockIdx.x] + 主机端累加）。

------------------------------------------------------------------------
1.4 bank 与 bank conflict
------------------------------------------------------------------------
    共享内存被硬件切成 32 个 bank，每个 bank 宽 4 字节，映射规则是：

        bank = (字节地址 / 4) % 32     ← 也就是「第几个 float」对 32 取模

          地址 float#0  #1  #2 ... #31  #32  #33 ...
          bank      0   1   2 ...  31     0    1  ...

    规则：一个 warp 的 32 个 lane，
      访问落在 32 个不同 bank → 一次搞定；
      多个 lane 撞进同一 bank（地址不同）→ 硬件必须串行化 = bank conflict。

    上面的代码为什么没有冲突：

        if (tid < s) sdata[tid] += sdata[tid + s];
                       ↑              ↑
                  lane 0..31      lane 0..31
                  bank 0..31      bank s..s+31 → 还是 32 个不同 bank

    两次访问都是「32 个 lane 打 32 个不同 bank」，一次事务完成，零冲突。
    （被淘汰的交错写法详见 2.5(3)(4)。）

------------------------------------------------------------------------
1.5 warp / SIMT：为什么 32 是魔法数
------------------------------------------------------------------------
    warp（线程束）= 硬件真正调度的最小单位，固定 32 个线程。

        一个 block（256 线程） = 8 个 warp
        ┌──warp0──┐┌──warp1──┐┌──warp2──┐ ... ┌──warp7──┐
        T0..T31    T32..T63   T64..T95        T224..T255

    「SIMT」= 单指令多线程：一个 warp 里的 32 个 lane 共用一套指令流。
    这带来两个直接后果：
      · blockSize 最好是 32 的倍数，否则最后一个 warp 有一半空转；
      · warp 内部天然「同步」—— 32 个 lane 同一时刻执行同一条指令。
        这正是 2.6 节敢省掉 __syncthreads 的物理依据。

------------------------------------------------------------------------
1.6 发散（divergence）：SIMT 最讨厌的东西
------------------------------------------------------------------------
    如果 warp 内的 lane 走了不同的分支：

        if (tid % 2 == 0) { A; } else { B; }

        lane 0,2,4,... 要走 A，lane 1,3,5,... 要走 B
        硬件只能：先带 16 个 lane 走 A（其余空转），再带另 16 个走 B
        → 本该 1 趟干完的活变成 2 趟，有效并行度腰斩

    这就是为什么主循环要写成 tid < s 而不是 tid % (2*s) == 0。

------------------------------------------------------------------------
1.7 __syncthreads()：block 级栅栏
------------------------------------------------------------------------
    语义：本 block 的「所有」线程都到达此点后，才允许任何一个继续；
    同时保证此前所有线程对共享内存的写，此后对所有线程可见。

        T0:  ─────写─────┃ 等 ┃──── 读 ────
        T1:  ─────写─────┃ 等 ┃──── 读 ────
        ...               ↑
        T255:─────写─────┃ 等 ┃──── 读 ────
                       所有线程都到达这里，才放行

    ⚠⚠ 两个必须记住的约束：
      ① 同一个 block 的所有线程都必须能到达这个点
         → 所以它永远不能写在条件分支里面（否则未定义行为 / 死锁）；
      ② 它只同步 block 内部，管不了别的 block，也管不了主机。

------------------------------------------------------------------------
1.8 volatile
------------------------------------------------------------------------
    一句话：告诉编译器「别把这个变量缓存进寄存器，
    每次都老老实实去内存读，并按我写的顺序读写」。

    为什么本文件需要它：因为编译器看不到「其他线程在改这块共享内存」，
    会误以为 sdata[tid] 只有自己会写，于是缓存到寄存器里 → 读到过期值。
    （详细展开见 2.6(3)。）


========================================================================
第 2 章　kernel 逐行详解
========================================================================

------------------------------------------------------------------------
2.1 函数签名
------------------------------------------------------------------------
    __global__ void reduceSum(const float* __restrict__ in,
                              float* __restrict__ out,
                              int n)

    与 vector_add 逐项对照：

        位置          vector_add         本文件                  说明
        ----------    ----------------   --------------------    ----------
        第 1 个参数   const float* a     const float* in         输入，只读
        第 2 个参数   const float* b     （无）                   只有一个输入数组
        第 3 个参数   float* c           float* out              不再是 N 个元素！
        第 4 个参数   int n              int n                   元素总数

    ⚠ 最重要的变化在第 3 个参数：out 的长度是 grid（block 个数），不是 N。

        vector_add:  c[0 .. N-1)        每个元素一个结果
        reduction:   out[0 .. grid-1)   每个 block 一个部分和

        N = 2^26, blockSize = 256
        → grid = 262144
        → out 只有 262144 个 float = 1 MiB（而不是 256 MiB！）

    这 262144 个部分和最后由 CPU 用 double 累加起来。

    __restrict__ 在本 kernel 里的作用：让编译器知道 in 和 out 不重叠，
    敢把 in[i] 的读取提前、合并。
    ⚠ 但 sdata 是共享内存，不受 __restrict__ 约束 ——
      编译器对它必须保守处理，这正是后面需要 volatile 的原因。

------------------------------------------------------------------------
2.2 extern __shared__ float sdata[];
------------------------------------------------------------------------
    这一行有三个知识点。

    (1) __shared__ —— 这块内存住在哪
        见 1.3。核心：每个 block 一份独立副本，block 之间互不可见。

    (2) extern —— 为什么用「动态」共享内存
        共享内存有两种声明方式：

            // 方式 A：静态 —— 编译期就知道大小
            __shared__ float sdata[256];      // 写死 256

            // 方式 B：动态 —— 运行期才知道大小（本文件用的）
            extern __shared__ float sdata[];  // 不写大小，用 extern 引导

        为什么用 B？因为 blockSize 是从命令行传进来的，
        编译期根本不知道是 128 还是 256 还是 512。
        extern 在这里的意思是：「这是一块外部声明的数组，
        具体多大等启动时再说，你先别自己分配。」

    (3) 大小必须由启动参数给 —— 忘了会怎样
        真正的大小在启动配置的第三个参数里：

            reduceSum<<<grid, blockSize, shmem>>>
                                    ↑
                              就是 sdata 的大小

        如果忘记写第三个参数（<<<grid, blockSize>>>），
        sdata 的大小 = 0 字节 → 往 0 字节的数组里写 → 非法内存访问。

            CUDA error ...: an illegal memory access was encountered

        ⚠ 这是动态共享内存最经典的坑：语法完全合法，运行时才炸。

------------------------------------------------------------------------
2.3 tid / i：我是谁，我该处理哪个元素
------------------------------------------------------------------------
    int tid = threadIdx.x;
    int i   = blockIdx.x * blockDim.x + tid;

        变量   含义              取值范围
        ----   ---------------   -----------------------
        tid    block 内编号      0 .. blockDim.x - 1
        i      全局编号          0 .. grid*blockDim - 1

    公式与 vector_add 完全相同，唯一区别是后面怎么用：

        vector_add: i 直接当数组下标，一个线程负责一个 c[i]
        reduction:  i 只用来「把数据搬进共享内存」，之后就完成使命了

                    sdata[tid] = in[i];
                           ↑        ↑
                    共享内存下标   全局内存下标

    ⚠⚠ 共享内存下标必须用 tid，不能用 i！
    因为 sdata 是 block 内的白板，长度只有 blockDim.x：

        block 1, tid 0  →  i = 256  →  sdata[256]  ← 越界！sdata 只有 0..255

    而 tid 的取值范围恰好是 0..blockDim.x-1，与 sdata 长度精确吻合。
    这是写 reduction 最容易搞混的地方，务必盯住。

------------------------------------------------------------------------
2.4 装载 + 边界补零
------------------------------------------------------------------------
    sdata[tid] = (i < n) ? in[i] : 0.0f;
    __syncthreads();

    (1) 为什么要补 0
        grid 是向上取整算出来的，最后一组往往有线程的 i >= n：

            n = 2^26 + 3, blockSize = 256
            grid = (n + 255)/256 = 262145
            最后一个 block 覆盖到 262145*256-1，比 n 大了 253 个

        ⚠ 这些越界线程不能直接 return：

            sdata[tid] = (i < n) ? in[i] : 0.0f;   ✅ 正确
            if (i < n) sdata[tid] = in[i];         ❌ sdata[tid] 留着垃圾值！

        第二种写法错在：共享内存是「未初始化」的，
        里面是上一个 kernel 留下的垃圾，这些垃圾会参与后续加法。

        补 0.0f 之所以安全，是因为 0 是加法的「单位元」：x + 0 = x。

        ⚠ 单位元因运算而异，换成别的归约必须改：

            求和      补 0.0f
            求最大值  补 -FLT_MAX     （不能用 0！否则最小值都变 0）
            求最小值  补 +FLT_MAX
            求乘积    补 1.0f

    (2) __syncthreads() 为什么必须有（这是全文件唯一一处绝对不能删的同步）

        不加栅栏的时间线：

            T0:  sdata[0] = in[0] ───────────────────────────┐
            T1:  sdata[1] = in[1] ─────────────────────┐     │
            T2:  sdata[2] = in[2] ──────────────┐      │     │
            ...                                  ↓      ↓     ↓
            T0:  sdata[0] += sdata[128]   ← 读到还没写好的 sdata[128]！💥

------------------------------------------------------------------------
2.5 主循环：kernel 的核心
------------------------------------------------------------------------
    for (int s = blockDim.x >> 1; s > 32; s >>= 1)
    {
        if (tid < s) sdata[tid] += sdata[tid + s];
        __syncthreads();
    }

    (1) >> 和 >>= 是什么
            blockDim.x >> 1   等价于 blockDim.x / 2   （右移一位 = 除以 2）
            s >>= 1           等价于 s = s / 2

        因为 blockDim.x 是 2 的幂（256），右移比除法更快，
        也更能表达「减半」的意图。

    (2) 用 blockSize = 256 走一遍

            轮次        s 的值   哪些线程干活        效果
            --------    ------   ----------------    ------------------------
            初始        —        —                   sdata[0..255] 装好原始数据
            第 1 轮     128      tid < 128（T0-T127）128 个数，每个是 2 个原始值之和
            第 2 轮     64       tid < 64（T0-T63）   64 个数
            循环退出    32（32>32 为假）—             剩 64 个数（sdata[0..63]）
            → 转由 2.6 节处理

        注意循环退出时还剩 64 个数，交给下面那个 if (tid < 32) 处理。

    (3) 为什么是 tid < s 而不是 tid % (2*s) == 0
        这是 reduction 优化史上最经典的一步。对比（blockSize=256，看第 1 轮）：

            ❌ 旧写法（交错寻址 interleaved）
               if (tid % (2 * s) == 0) sdata[tid] += sdata[tid + s];

               一个 warp（32 个 lane）内部（s=1 时）：
               ┌───────────────────────────────┐
               │■□■□■□■□■□■□■□■□■□■□■□■□■□■□│  ← 16 个动、16 个停
               └───────────────────────────────┘
               这就是「线程发散」：硬件要把两条路径都走一遍 → 并行度腰斩

            ✅ 新写法（顺序寻址 sequential）
               if (tid < s) sdata[tid] += sdata[tid + s];

               每个 warp 内 32 个 lane 全动 → 无发散

        ⚠ 一个「按下葫芦浮起瓢」的故事：
          有人为了消除发散，改成 index = 2*s*tid 的乘法寻址（不发散了），
          结果引入了 bank conflict —— 见 (4)。
          真正把两个坑一起填掉的是 tid < s 的顺序寻址。

    (4) bank conflict 与顺序寻址的第二个好处
        见 1.4 的 bank 映射规则。

        被淘汰的写法在 s = 16 时：

            index = 32 * tid  →  lane 0 访问 float#0
                                 lane 1 访问 float#32
                                 lane 2 访问 float#64
                                 ...
            全部落在 bank 0！→ 32-way bank conflict → 串行 32 次 💥

        而 sdata[tid] += sdata[tid + s] 每轮都是 32 个 lane
        打 32 个不同 bank，零冲突。
        所以顺序寻址同时解决「发散」和「bank conflict」两个问题。

    (5) 为什么不能把 __syncthreads() 挪进 if 里

            // ❌ 绝对不能这么写
            if (tid < s) {
                sdata[tid] += sdata[tid + s];
                __syncthreads();       // 一半线程到不了这里！
            }

        回到 s=128 那一轮：T0-T127 会执行 __syncthreads()，
        T128-T255 永远不会执行到。而它的语义是「所有线程都到达」。

        后果：未定义行为。实践中最常见是「死锁」（GPU 挂住，
        程序卡死到超时），但在某些架构上会「碰巧能跑但结果不对」——
        后者更可怕，因为它会伪装成「偶尔出错」。

            T0  : ──干活──┃ 等 等 等 等 等 ...
            T128: ──空转  ✗ 永远不来
                          ↑ barrier 永远不满足 → 死锁

        口诀：__syncthreads() 永远写在条件分支外面。

------------------------------------------------------------------------
2.6 展开最后一个 warp
------------------------------------------------------------------------
    if (tid < 32)
    {
        volatile float* v = sdata;
        v[tid] += v[tid + 32];
        v[tid] += v[tid + 16];
        v[tid] += v[tid +  8];
        v[tid] += v[tid +  4];
        v[tid] += v[tid +  2];
        v[tid] += v[tid +  1];
    }

    从主循环退出时，sdata[0..63] 里是 64 个中间结果。
    这一段用 6 条语句把它归约成 1 个。

    (1) 为什么可以不再写 __syncthreads()
        关键事实：一个 warp 的 32 个 lane 是硬件调度的最小单位，
        它们天然执行同一套指令。而这里干活的恰好正好是 1 个 warp。

            主循环：T0..T127 干活 → 横跨 4 个 warp → warp 之间必须栅栏
                    ┌──warp0──┐┌──warp1──┐┌──warp2──┐┌──warp3──┐
                    T0..T31    T32..T63   T64..T95   T96..T127

            最后一步：T0..T31 干活 → 只有 1 个 warp → 内部天然同步 ✅
                    ┌──warp0──┐
                    T0..T31

        省掉了 6 次 __syncthreads()。别小看 ——
        这是 block 级栅栏，在 262144 个 block 上乘 6 次是可观的开销。

    (2) 6 条语句分别对应哪一步

            语句                     等价于主循环里的   效果
            ----------------------   ----------------   --------
            v[tid] += v[tid + 32];   s = 32             64 → 32
            v[tid] += v[tid + 16];   s = 16             32 → 16
            v[tid] += v[tid +  8];   s = 8              16 → 8
            v[tid] += v[tid +  4];   s = 4              8  → 4
            v[tid] += v[tid +  2];   s = 2              4  → 2
            v[tid] += v[tid +  1];   s = 1              2  → 1

        如果不用展开、老老实实写循环，就是：

            for (int s = 32; s > 0; s >>= 1) {
                if (tid < s) sdata[tid] += sdata[tid + s];
                __syncthreads();      // ← 6 次栅栏，全都可以省
            }

        结果一样，但慢。这就是「展开（unroll）」的价值：
        用代码长度换掉同步开销。

        ⚠ 「最后一个 warp」指的是「归约到只剩最后一个 warp 在干活」
          的那个阶段，不是「编号最大的那个 warp」。

    (3) volatile —— 这一段最容易漏的关键字

            volatile float* v = sdata;      ✅
            float* v = sdata;               ❌ 可能算错

        为什么需要它？因为编译器根本不知道有其他线程在改 sdata。

        编译器视角（它以为这是单线程程序）：
            v[tid] += v[tid + 32];   读 v[tid+32]
            v[tid] += v[tid + 16];   读 v[tid+16]
            → 「既然 v[tid] 我自己刚写过，别人又不可能改它，
               那我就把它缓存在寄存器里，省几次内存访问。」

        但它错在：v[tid] 会被别的线程改写（lane tid-32 会读它，
        更小的 lane 会累加到它上面）。于是优化后变成：

            寄存器 r = v[tid+32];     ← 只在最开始读一次
            r += v[tid+16];           ← 从寄存器读，读到的是旧值 💥

        volatile 的作用就是一句话：别缓存，每次都真的去内存读，
        并且按我写的顺序读写。

        ⚠ 现代补充（Volta / sm_70 之后）：同一个 warp 内的 lane
          可以独立推进（ITS），所以官方更严格的写法是加 __syncwarp()：

              if (tid < 32) {
                  volatile float* v = sdata;
                  v[tid] += v[tid + 32];
                  ...
                  __syncwarp();        // 显式同步 warp 内 lane
              }

          在本文件中 if (tid < 32) 对 warp 0 是一致条件（全真），
          没有发散，所以老的 volatile 写法在实践中仍然正确。
          但如果你以后在「有发散的」warp 内做这种操作，
          volatile 就不够了，必须加 __syncwarp()。

    (4) 隐藏约束：这段代码要求 blockSize >= 64

            blockSize = 64  → 主循环 s=32 时一次都不跑；
                              最后 warp 执行 v[tid] += v[tid+32]
                              访问 sdata[32..63] ✅ 合法（sdata 长度正好 64）

            blockSize = 32  → 主循环一次都不跑；
                              最后 warp 访问 sdata[32..63] 💥 越界！
                              （sdata 长度只有 32）

        所以本 kernel 要求 blockSize >= 64。传 128/256/512/1024 都安全。
        （若非要支持 32，得把展开改成从 v[tid+16] 开始。）

------------------------------------------------------------------------
2.7 交出部分和
------------------------------------------------------------------------
    if (tid == 0) out[blockIdx.x] = sdata[0];

    (1) 为什么用 blockIdx.x 当下标

            block  0      → out[0]
            block  1      → out[1]
            block  2      → out[2]
            ...
            block  grid-1 → out[grid-1]

        每个 block 一个格子，互不重叠。out 的长度就是 grid
        （第 72 行的 cudaMalloc 按 grid * sizeof(float) 分配），不会越界。

        这种「每个 block 自己算出生意、写到专属格子」的模式，
        是 CUDA 里最常用的「两级归约」套路。

    (2) 为什么只让 tid == 0 写
        归约结果只有一个，不能 256 个线程都去写 out[blockIdx.x]：
          · 只有 1 次全局内存写 → 流量可忽略；
          · 不会产生写-写竞争（多个线程写同一地址未定义）。

    (3) 这里为什么不需要再加 __syncthreads()
        因为写 sdata[0] 的就是 tid 0 自己（最后一条 v[0] += v[1]
        是 tid 0 执行的），同一个线程读自己刚写的值，天然有序。


