第 9 章　可以改进的地方（留给自己动手）
========================================================================

    ① 【正确性】返回值没反映验证结果
           return 0;                                  // 现状
           return (fabs(sum - ref) <= 1e-3) ? 0 : 1;  // 建议
        改完后 ./reduction && echo OK 才真的有意义，方便写自动化脚本。

    ② 【健壮性】blockSize 没有校验

           if (blockSize < 64 || blockSize > 1024 || (blockSize & 31) != 0) {
               fprintf(stderr, "blockSize must be a multiple of 32 in [64,1024]\n");
               return 1;
           }

        理由见 2.6(4) 与 3.1。让程序在传错参数时立刻说清楚，
        而不是让 kernel 静默失败。

    ③ 【性能】加一个 grid-stride 版本来对比
        本 kernel 的 grid = 262144 个 block，远超 SM 能同时承载的量
        （本机 24 SM x 24 block = 576），要分 455 批才跑完。
        每一波结束都有 block 启动/退休的开销。
        可以在同一个文件里加一个 grid-stride 预累加的版本做对照。

    ④ 【性能】把共享内存归约换成 warp shuffle
        现代写法是块内全程用 __shfl_down_sync，连 sdata 都不需要
        （除了 warp 之间那一小步），省掉大量共享内存访问和栅栏。
        打好当前版本后，这是最自然的下一步。

    ⑤ 【扩展】把归约改成求最大值（最小改动，但能真正理解「单位元」）

           #include <cfloat>
           sdata[tid] = (i < n) ? in[i] : -FLT_MAX;                    // 单位元
           if (tid < s) sdata[tid] = fmaxf(sdata[tid], sdata[tid + s]); // 运算
           // 主机端：sum 初值 -FLT_MAX，用 fmaxf 累加

    ⑥ 【健壮性】atoi 不做错误检查：atoi("abc") 会静默返回 0。
        想严谨可以用 strtol 并检查 endptr。

    ⑦ 【风格】用相对误差替代绝对容差（见 5.3(1)）。


