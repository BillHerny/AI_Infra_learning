#include <cstdio>
#include <cstdlib>
#include <cmath>
#include <cuda_runtime.h>

#define CUDA_CHECK(call)                                          \
    do{                                                           \
        cudaError_t err = (call);                                 \
        if(err != cudaSuccess){                                   \
            fprintf(stderr, "CUDA error %s:%d: %s\n",             \
                   __FILE__, __LINE__, cudaGetErrorString(err));  \
            exit(EXIT_FAILURE);                                   \
        }                                                         \
    }while(0)

// ============ KERNEL : 一个 block 归约出一段数据的和 ============
__global__ void reduceSum(const float* __restrict__ in,
                          float* __restrict__ out,
                          int n)
{
    extern __shared__ float sdata[];        // 动态共享内存，大小由 <<<>>> 第三个参数决定

    int tid = threadIdx.x;
    int i   = blockIdx.x * blockDim.x + tid;

    sdata[tid] = (i < n) ? in[i] : 0.0f;    // 越界补 0，0 不影响求和
    __syncthreads();                        // 等全 block 把数据放好

    // 顺序寻址：只有前 s 个线程干活，后半整齐空转（不发散）
    for (int s = blockDim.x >> 1; s > 32; s >>= 1)
    {
        if (tid < s) sdata[tid] += sdata[tid + s];
        __syncthreads();                    // 注意：同步必须在 if 外面
    }

    // 最后一个 warp：同 warp 内本就 SIMT 同步，手动展开、无需 __syncthreads
    if (tid < 32)
    {
        volatile float* v = sdata;          // volatile 阻止编译器缓存进寄存器
        v[tid] += v[tid + 32];
        v[tid] += v[tid + 16];
        v[tid] += v[tid +  8];
        v[tid] += v[tid +  4];
        v[tid] += v[tid +  2];
        v[tid] += v[tid +  1];
    }

    if (tid == 0) out[blockIdx.x] = sdata[0];   // 每个 block 交出一个部分和
}

int main(int argc, char** argv)
{
    int n         = (argc > 1) ? atoi(argv[1]) : (1 << 26);
    int blockSize = (argc > 2) ? atoi(argv[2]) : 256;

    size_t bytes = (size_t)n * sizeof(float);
    int    grid  = (n + blockSize - 1) / blockSize;   // 一线程一元素

    // ---- host 数据：全填 1.0f，精确和就是 n ----
    float* h_a = (float*)malloc(bytes);
    for (int i = 0; i < n; i++) h_a[i] = 1.0f;

    double ref = 0.0;
    for (int i = 0; i < n; i++) ref += h_a[i];

    printf("N = %d (%.1f MiB), grid = %d, blockSize = %d\n",
           n, bytes / 1024.0 / 1024.0, grid, blockSize);

    // ---- device 内存 ----
    float *d_a, *d_out;
    CUDA_CHECK(cudaMalloc(&d_a, bytes));
    CUDA_CHECK(cudaMalloc(&d_out, (size_t)grid * sizeof(float)));
    CUDA_CHECK(cudaMemcpy(d_a, h_a, bytes, cudaMemcpyHostToDevice));

    size_t shmem = (size_t)blockSize * sizeof(float);

    // ---- warm-up ----
    reduceSum<<<grid, blockSize, shmem>>>(d_a, d_out, n);
    CUDA_CHECK(cudaGetLastError());
    CUDA_CHECK(cudaDeviceSynchronize());

    // ---- 计时 ----
    cudaEvent_t start, stop;
    CUDA_CHECK(cudaEventCreate(&start));
    CUDA_CHECK(cudaEventCreate(&stop));

    const int iters = 20;
    float best = 1e30f;
    for (int k = 0; k < iters; k++)
    {
        CUDA_CHECK(cudaEventRecord(start));
        reduceSum<<<grid, blockSize, shmem>>>(d_a, d_out, n);
        CUDA_CHECK(cudaEventRecord(stop));
        CUDA_CHECK(cudaEventSynchronize(stop));

        float ms = 0.0f;
        CUDA_CHECK(cudaEventElapsedTime(&ms, start, stop));
        if (ms < best) best = ms;
    }

    // ---- 取回部分和，host 用 double 累加 ----
    float* h_partial = (float*)malloc((size_t)grid * sizeof(float));
    CUDA_CHECK(cudaMemcpy(h_partial, d_out, (size_t)grid * sizeof(float),
                          cudaMemcpyDeviceToHost));
    double sum = 0.0;
    for (int i = 0; i < grid; i++) sum += (double)h_partial[i];

    printf("reference (double) = %.0f\n", ref);
    printf("gpu sum            = %.0f\n", sum);
    printf("verify: %s\n", fabs(sum - ref) <= 1e-3 ? "PASS" : "FAIL");
    printf("best time = %.4f ms\n", best);
    printf("bandwidth = %.1f GB/s\n", (bytes / 1e9) / (best / 1e3));

    free(h_a);
    free(h_partial);
    CUDA_CHECK(cudaFree(d_a));
    CUDA_CHECK(cudaFree(d_out));
    CUDA_CHECK(cudaEventDestroy(start));
    CUDA_CHECK(cudaEventDestroy(stop));
    return 0;
}

