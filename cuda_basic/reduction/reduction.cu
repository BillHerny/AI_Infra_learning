第 7 章　执行流程一览
========================================================================

    CPU 侧（主机）                                  GPU 侧（设备）
    -----------------------------------------     ---------------------------
    1. 解析 N、blockSize
    2. grid = ceil(N/blockSize)
    3. malloc h_a，填 1.0f
    4. 串行算 ref（double）
    5. cudaMalloc d_a（N 个）、d_out（grid 个）
    6. cudaMemcpy  h_a -> d_a                   -> （输入搬入显存）
    7. shmem = blockSize * 4
    8. 启动 kernel（warm-up）                   ->  ┌──────────────────────┐
       cudaGetLastError()                           │ 每个 block：          │
       cudaDeviceSynchronize()                <-    │  ① 搬数据进 sdata     │
                                                    │  ② s=128,64 两轮树形  │
    9. 循环 20 次：                                 │  ③ 最后 warp 展开 6 步│
       record(start)                                │  ④ tid0 写 out[bid]   │
       启动 kernel                            ->    └──────────────────────┘
       record(stop)                                          ↓
       synchronize(stop)                            out[0..grid-1] 部分和
       elapsedTime -> 取最小                        （1 MiB）
   10. cudaMemcpy  d_out -> h_partial           <- （1 MiB 搬回）
   11. double 累加 -> sum
   12. 对比 ref -> PASS / FAIL
   13. 打印耗时、带宽
   14. free / cudaFree / cudaEventDestroy

    数据规模的变化轨迹（这是理解本 kernel 的关键）：

        256 MiB          256 MiB         1 MiB            1 个数
        a[0..N)  ─搬入→  d_a  ─kernel→  d_out  ─搬回→  h_partial ─CPU→ sum
        （N 个）                        （grid 个）      （grid 个）    （1 个）
                                            ↑
                                  缩小了 blockSize = 256 倍


========================================================================
第 8 章　常见误解 & 卡点清单
========================================================================

    #   误解 / 卡点                            正确认识
    --   -----------------------------------   --------------------------------
    1    共享内存下标可以用全局编号 i          ❌ 必须用 tid。sdata 只有
                                                  blockDim.x 长，用 i 会越界
    2    越界的线程直接 return 就行            ❌ 必须补「单位元」（求和补 0），
                                                  否则 sdata[tid] 留垃圾值参与加法
    3    __syncthreads() 放进 if 里也没事      ❌ 未定义行为，常见表现是死锁
    4    第一个 __syncthreads() 可以省          ❌ 必须有，否则会读到其他线程
                                                  还没写入的 sdata
    5    最后一个 warp 也要 __syncthreads      ✅ 可以省（同 warp 天然同步），
                                                  但必须加 volatile
    6    volatile 加不加都行                  ❌ 不加可能读到寄存器里的旧值
    7    静态/动态共享内存只是写法不同         动态的大小必须由启动参数给，
                                                  忘了就是 0 字节
    8    本 kernel 传 blockSize = 32 也可以    ❌ 要求 blockSize >= 64
    9    带宽要乘 3（顺手抄 vector_add）       ❌ reduction 只读一遍输入 -> 乘 1
    10   GPU 用 float，肯定比 CPU 的 double 粗糙 ✅ 本示例反而完全精确 ——
                                                  中间值都是 2 的幂 + 部分和用
                                                  double 累加
    11   主机端累加太慢，应该再写个 kernel      262144 个数 CPU 串行加完 ~0.1 ms，
                                                  比再启一个 kernel 更划算
    12   verify: PASS 就说明一切正常           ❌ 还要看带宽是否合理 ——
                                                  kernel 没跑也可能 PASS
    13   求最大值也可以用 0.0f 补零            ❌ 那是求和/乘积的单位元，
                                                  求最大值要补 -FLT_MAX

------------------------------------------------------------------------
三条「最容易卡住」的排查路径
------------------------------------------------------------------------
    现象 A：结果比正确答案小几倍
      -> 检查 ① 越界线程有没有补单位元（sdata[tid] = ... : 0.0f）
              ② 主机端累加是不是用了 float 而不是 double

    现象 B：程序挂住 / 超时（不是崩溃，是卡死）
      -> 检查 __syncthreads() 是不是被写进了 if 里

    现象 C：verify 偶尔 PASS 偶尔 FAIL
      -> 检查 volatile 是不是漏了


