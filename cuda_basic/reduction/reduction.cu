------------------------------------------------------------------------
6.1 三组配对原则
------------------------------------------------------------------------
        malloc           <->  free               本文件：2 次 -> 2 次  ✅
        cudaMalloc       <->  cudaFree           本文件：2 次 -> 2 次  ✅
        cudaEventCreate  <->  cudaEventDestroy   本文件：2 次 -> 2 次  ✅

    对照检查方法：数一下「申请」出现了几次，就要求「释放」也出现几次。

    与 vector_add.cu 的区别：那边有 4 次 malloc + 3 次 cudaMalloc；
    本文件只有 2 次 malloc（h_a / h_partial）+ 2 次 cudaMalloc（d_a / d_out）——
    因为不需要 h_b（只有一个输入数组），
    也不需要单独的 ref 数组（参考值是一个标量）。

------------------------------------------------------------------------
6.2 为什么 cudaFree(d_a) 传 d_a，而 cudaMalloc(&d_a, ...) 传 &d_a
------------------------------------------------------------------------
        API                        传什么        为什么
        ------------------------   -----------   ----------------------------
        cudaMalloc(&d_a, bytes)    地址的地址    要「回写」d_a（写入新地址）
        cudaFree(d_a)              地址本身      只是按地址释放，不回写变量
        cudaEventCreate(&start)    地址的地址    要回写 start
        cudaEventDestroy(start)    地址本身      只销毁，不回写

    一句话判据：函数要不要「修改你这个变量」？要 → 传 &；不要 → 直接传。

------------------------------------------------------------------------
6.3 return 0
------------------------------------------------------------------------
        0     -> 成功（shell 里 echo $? 得到 0）
        非 0   -> 失败

    ⚠ 本文件的一个真实缺陷：即使 verify: FAIL，程序仍然 return 0。

        ./build/bin/reduction && echo "成功了"
        → 即使算错了也会打印「成功了」

    自动化脚本 / CI 无法通过退出码发现「结果不对」。
    更规范的做法：

        return (fabs(sum - ref) <= 1e-3) ? 0 : 1;

    这是「可以改进的地方」里最值得改的一条（见第 9 章）。


