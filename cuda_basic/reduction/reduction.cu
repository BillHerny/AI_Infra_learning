------------------------------------------------------------------------
5.1 取回部分和
------------------------------------------------------------------------
    float* h_partial = (float*)malloc((size_t)grid * sizeof(float));
    CUDA_CHECK(cudaMemcpy(h_partial, d_out, (size_t)grid * sizeof(float),
                          cudaMemcpyDeviceToHost));

    ⚠ 注意搬回的量不是 bytes！

        vector_add : cudaMemcpy(h_c, d_c, bytes, ...)              ← 256 MiB
        本 reduction: cudaMemcpy(h_partial, d_out, grid*4, ...)     ← 1 MiB

    只搬回 1 MiB（262144 个部分和）。这是两级归约的额外收益：
    D2H 传输量缩小了 blockSize 倍，从 ~22 ms 降到 ~0.1 ms。

    （回忆 my_vector_add 踩的坑：D2H 慢是因为 malloc 的内存从没被写过，
      会触发缺页中断。这里 1 MiB 太小，无关痛痒；
      要追求极致可以用 cudaHostAlloc 锁页。）

------------------------------------------------------------------------
5.2 主机端最终归约
------------------------------------------------------------------------
    double sum = 0.0;
    for (int i = 0; i < grid; i++) sum += (double)h_partial[i];

    (1) 为什么最后一步放在 CPU，而不是再写一个 kernel

        因为已经不划算了：

            再写一个 kernel 归约 262144 个部分和：
                要再启动一次 kernel（~5 us 启动开销）+ 一次同步
                → 比 CPU 串行加 262144 次（约 0.1~0.3 ms）还贵或相当

            CPU 串行累加：
                262144 次 double 加法，约 0.1~0.3 ms，
                不占 GPU、不引入同步 → 更简单、更快 ✅

        判断准则：当剩余数据量已经很小（万级），
        搬回 CPU 处理往往比再启一个 kernel 划算。

    (2) 为什么写 (double) 转换
        C++ 的算术转换规则会自动把 float 提升为 double
        （double + float → double），所以显式写 (double) 是「明示」而非「必需」。

        但强烈建议写明，理由有二：
          ① 防止以后手滑把 sum 改成 float —— 那时 (double) 会立刻提醒你；
          ② 可读性：读者一眼看出「这里的累加是刻意用 double 的」。

    (3) 为什么不能直接比较 h_partial[i] 和 GPU 上的 d_out[i]
        与 vector_add 专题 7 完全一样：CPU 读不到设备指针。
        d_out[i] 在主机代码里是非法访问，会 segfault；
        而且编译器不报错（因为 float* 类型上合法）。

