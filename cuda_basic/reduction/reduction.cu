5.3 打印与验证
------------------------------------------------------------------------
    printf("reference (double) = %.0f\n", ref);
    printf("gpu sum            = %.0f\n", sum);
    printf("verify: %s\n", fabs(sum - ref) <= 1e-3 ? "PASS" : "FAIL");
    printf("best time = %.4f ms\n", best);
    printf("bandwidth = %.1f GB/s\n", (bytes / 1e9) / (best / 1e3));

        格式符   作用
        -------   ------------------------------------------
        %.0f      打印小数但不带小数位（和是整数，更好读）
        %s        打印字符串（"PASS" / "FAIL"）
        %.4f      毫秒保留 4 位（比 vector_add 的 %.3f 更能看出波动）
        %d        整数

    (1) 关于容差 1e-3
        为什么敢用这么严的容差？因为 3.3(3) 分析过：
        全为 1 + 树形归约 + double 累加 = 完全精确，误差恰好为 0。

        但更通用的写法应该用「相对误差」：

            // 推荐你自己改一下试试
            double err = fabs(sum - ref) / (fabs(ref) + 1e-12);
            printf("verify: %s (rel err = %.3e)\n",
                   err <= 1e-5 ? "PASS" : "FAIL", err);

        因为绝对容差 1e-3 只在「和大约为 6.7e7」时合理：
          · N 改成 100，和只有 100，1e-3 过严；
          · N 改成 2^30，和到 1e9，1e-3 又过松。
        判据：比较浮点结果时，优先用相对误差。

    (2) 关于 fabs 而不是 fabsf
        sum 和 ref 都是 double，所以必须配 double 版的 fabs。
        规则：float 配 fabsf，double 配 fabs，别混。

        （注意与 vector_add.cu 的差异：那边比较的是 float，所以用 fabsf。）

    (3) ⚠ 一个真实的坑：PASS 但带宽离谱

            verify: PASS
            best time = 0.0312 ms          ← 太快了！
            bandwidth = 8226.9 GB/s        ← 超过峰值 32 倍 💥

        这说明 kernel 根本没跑（grid 算错 / 没查 cudaGetLastError），
        或者你只测了部分数据。
        口诀：先看 verify，再看带宽；带宽超峰值 → 立刻怀疑代码，别高兴。


