附录 A　「五步走」口诀
========================================================================

    ① 搬进白板    sdata[tid] = (i<n) ? in[i] : 单位元;
    ② 竖栅栏      __syncthreads();                 ← 必须有
    ③ 逐轮减半    for (s = blockDim/2; s > 32; s >>= 1)
                      if (tid < s) sdata[tid] += sdata[tid + s];
                      __syncthreads();             ← 必须在 if 外面
    ④ 收尾一个 warp  if (tid < 32) { volatile; 手动展开 6 步 }
    ⑤ 交出结果    if (tid == 0) out[blockIdx.x] = sdata[0];

    配套的四个「为什么」：
      为什么用 tid 索引？    因为 sdata 只有 blockDim 长
      为什么要补单位元？      因为越界线程必须贡献「无害」的值
      为什么停在 32？        因为一个 warp 内部天然同步，不必再栅栏
      为什么要 volatile？     因为编译器不知道别的线程在改共享内存


