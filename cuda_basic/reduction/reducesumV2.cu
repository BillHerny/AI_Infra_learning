      for (int k = 0; k < iters; k++) {
          CUDA_CHECK(cudaEventRecord(start));
          reduceSum<<<grid, blockSize, shmem>>>(d_a, d_out, n);
          CUDA_CHECK(cudaEventRecord(stop));
          CUDA_CHECK(cudaEventSynchronize(stop));      // ← 必须有
          float ms = 0.0f;
          CUDA_CHECK(cudaEventElapsedTime(&ms, start, stop));
          if (ms < best) best = ms;                    // ← 取最小
      }

    · kernel 是**异步**的（CPU 发完命令立刻往下走），
      所以必须在 elapsedTime 之前先 cudaEventSynchronize(stop)
    · 取 20 次里**最小**的：GPU 会因为温度升而降频，降频只会让时间变长，
      所以最快那次最接近硬件上限

