4.3 数据与参考值
------------------------------------------------------------------------
      float* h_a = (float*)malloc(bytes);
      for (int i = 0; i < n; i++) h_a[i] = 1.0f;      // 全填 1

      double ref = 0.0;
      for (int i = 0; i < n; i++) ref += h_a[i];       // CPU 算标准答案

  两个细节：

    · 全填 1.0f → 正确答案就是 n，肉眼一查便知
    · ref 用 **double**：如果也用 float 累加，加到 16777216（= 2^24）
      之后就再也加不动 1 了（float 在这个量级的最小间隔是 2），
      最后只会得到 16777216，**差 4 倍**。

