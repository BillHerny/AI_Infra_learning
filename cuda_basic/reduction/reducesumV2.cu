========================================================================
第 0 步　先不看代码，先看问题
========================================================================

  我们要做的事：把 67108864（= 2^26）个数加起来，得到 1 个数。

      输入：a[0] a[1] a[2] ... a[67108863]
      输出：一个数

  难点在哪？如果只让 1 个线程从头加到尾，那只是把 CPU 的慢搬到 GPU 上。
  GPU 的价值是「并行」，但「求和」天生是「往下汇合」的 ——
  1000 个人算出来的 1000 个数，最后得合成 1 个数。

  所以整个算法的核心只有一句话：

      **分三层，一层一层往下合。**

      第 1 层：每个线程  把自己手里的几个数 → 加成一个数   （67108864 → 8388608）
      第 2 层：每个 block 把 256 个线程的数  → 加成一个数   （8388608  → 32768）
      第 3 层：CPU       把 32768 个部分和  → 加成一个数   （32768     → 1）

  看懂上面这张「数量表」，V2 的结构就懂了 80%。


========================================================================
第 1 步　四种「存东西的地方」
========================================================================

  后面所有代码都在倒腾这四种地方，先分清它们：

      名字        在哪            谁能访问              速度        代码里长什么样
      --------    ------------    ------------------    --------    --------------------
      全局内存    显存（8 GB）    所有线程 + CPU 拷贝   慢(DRAM)    in[]、out[]（d_ 前缀）
      共享内存    GPU 芯片上      同一个 block 的线程   快          __shared__ float sdata[]
      寄存器      GPU 芯片上      只有本线程自己        最快        普通的 float sum;
      主机内存    内存条          CPU                   —           h_a、h_partial（h_ 前缀）

  ⚠ 关键限制：寄存器是**私有**的 —— 线程 5 看不到线程 6 的 sum。

  这就是为什么必须有「共享内存」这个中间站：
      想跨线程合并数据，就必须找个大家都能读写的地方。


========================================================================
第 2 步　必须先搞懂：grid-stride 循环
========================================================================

  这是 V2 和 V1 唯一的区别所在，也是最容易卡住的地方。

------------------------------------------------------------------------
2.1 先看「笨办法」：一个线程一个元素
------------------------------------------------------------------------
      a 数组：  [0][1][2][3][4][5] ...
      线程：     T0 T1 T2 T3 T4 T5 ...      ← 每个线程只读 1 个

      要 67108864 个元素，就需要 67108864 个线程 = 262144 个 block。

  问题：每个 block 只搬 256 个 float = 1 KiB 数据，然后就要同步、归约、退出。
       启动 / 退休 / 同步的开销占比太高。
       —— 这就是 V1 慢的原因（实测只有 ~150 GB/s，而峰值是 256 GB/s）。

------------------------------------------------------------------------
2.2 再看 V2 的做法：一个线程读好几个
------------------------------------------------------------------------
      让每个线程读 8 个：

        线程 T0 读：a[0]      a[8388608]  a[16777216] ... （共 8 个）
        线程 T1 读：a[1]      a[8388609]  a[16777217] ... （共 8 个）
        线程 T2 读：a[2]      a[8388610]  a[16777218] ... （共 8 个）
          ...

      于是只需要 8388608 个线程 = 32768 个 block（比之前少 8 倍）。

------------------------------------------------------------------------
2.3 那个「步长 8388608」是怎么来的？
------------------------------------------------------------------------
      8388608 = 总线程数 = grid(32768) × blockSize(256)
              = blockDim.x × gridDim.x        ← 代码里写的就是这个

  为什么步长要等于总线程数？因为这样「一轮」循环，全体线程正好覆盖连续的一段：

      第 1 轮：全体线程读 [0,        8388608)    ← 连续 32 MiB
      第 2 轮：全体线程读 [8388608,  16777216)   ← 连续 32 MiB
      第 3 轮：全体线程读 [16777216, 25165824)   ← 连续 32 MiB
        ...
      第 8 轮：全体线程读 [58720256, 67108864)   ← 连续 32 MiB

  ⚠ 这里有个非常容易误解的点：

      · 单个线程读的 8 个元素是**分散的**（相隔 8388608 个位置）
      · 但每一轮里，全体线程合起来读的是一段**连续**的内存

    对 DRAM 来说，重要的是后者 —— 每一轮都是一次漂亮的连续扫描，
    所以性能不受影响。

------------------------------------------------------------------------
2.4 用一行代码读懂它
------------------------------------------------------------------------
      for (int i = blockIdx.x * blockDim.x + tid;   // 我的「起始下标」
           i < n;                                    // 没越界就继续
           i += blockDim.x * gridDim.x)              // 每次跨「整个 grid 的宽度」
      {
          sum += in[i];
      }

  用具体数字走一遍（blockSize=4、grid=2 → 步长 = 8；n = 20）：

      T0 的下标：0 → 8  → 16 → (24 越界，停)     读了 3 个
      T1 的下标：1 → 9  → 17 → 停
      T2 的下标：2 → 10 → 18 → 停
      T3 的下标：3 → 11 → 19 → 停
      T4 的下标：4 → 12 → (20 越界，停)          读了 2 个
      ...
      T7 的下标：7 → 15 → 停

  看到没：8 个线程、三轮循环，把 20 个元素全读完了，一个不漏、一个不重。
  而且条件 i < n 天然就把越界挡住了。


========================================================================
第 3 步　kernel 逐行
========================================================================

------------------------------------------------------------------------
3.1 函数签名
------------------------------------------------------------------------
      __global__ void reduceSum(const float* __restrict__ in,
                                float* __restrict__ out,
                                int n)

      部分               含义
      ---------------    ----------------------------------------------------
      __global__         这是「在 GPU 上跑、由 CPU 启动」的函数
      void               不通过 return 返回结果
                         （几万个线程同时跑，返回值给谁？）
      const float* in    输入数组。const = 我保证不改它
      float* out         输出。长度是 **grid**，不是 n        ← 注意！
      int n              元素总数

  ⚠ **out 的长度是 grid（32768），不是 n（67108864）**。
    因为它存的是「每个 block 一个部分和」，最后交给 CPU 合。

------------------------------------------------------------------------
3.2 拿到共享内存
------------------------------------------------------------------------
      extern __shared__ float sdata[];

  拆开读：

      __shared__   这块内存在「共享内存」层，**同一个 block 的线程都能读写**
      extern       大小**不写在这里**，等启动 kernel 时再告诉它多大
      sdata[]      大小待定的一排 float

  有多大？在 main 里：

      size_t shmem = (size_t)blockSize * sizeof(float);   // 256 × 4 = 1024 字节
      reduceSum<<<grid, blockSize, shmem>>>(d_a, d_out, n);
                                   ↑
                            第三个参数就是 sdata 的大小

  所以 sdata 有 256 个位置，**正好对应这个 block 的 256 个线程**。
  这是它后面能用 tid 当下标的原因。

  ⚠ extern __shared__ 的约定：一个文件里所有「动态共享内存」共用同一块空间，
    所以文件里多个 kernel 都声明 sdata 不会冲突（它们不会同时跑）。

------------------------------------------------------------------------
3.3 我是谁
------------------------------------------------------------------------
      int tid = threadIdx.x;

  tid = 本线程在**本 block 内**的编号，范围 0 ~ 255。

  ⚠ 注意这里**没有**算全局编号（V1 里那行
       int i = blockIdx.x * blockDim.x + tid;
    被删掉了）。因为 V2 里「全局编号」在循环里一条一条地生成，
    不需要预先算好。

------------------------------------------------------------------------
3.4 【V2 的核心】寄存器内累加
------------------------------------------------------------------------
      float sum = 0.0f;                    // ← 普通变量，住在【寄存器】里
      for (int i = blockIdx.x * blockDim.x + tid;
           i < n;
           i += blockDim.x * gridDim.x)
      {
          sum += in[i];                    // 每次读完就加进自己的 sum
      }

  这一小段就是 V2 相对 V1 的**全部改动**。逐点解释：

  (a) float sum = 0.0f; 为什么初值是 0？

      因为代码是**求和**，而 0 是加法的**单位元**：

          x + 0 = x

      意思是「往里面加任何数都不会改变结果」。所以：

        · 如果某个线程因为循环条件一次都没进来（N 很小、线程很多），
          它的 sum 保持 0.0f；
        · 这个 0.0f 混进后面的加法里，**完全无害**。

      ⚠ 这一点是后面 sdata[tid] = sum; 不再需要写边界判断的原因
        （V1 里那句 (i < n) ? in[i] : 0.0f 消失了）。

      ⚠ **单位元是跟着「运算」变的**，这点极其重要：

          运算        单位元        为什么
          --------    ----------    ----------------
          求和        0.0f          x + 0 = x
          求最大值    -FLT_MAX      max(x, -∞) = x
          求乘积      1.0f          x × 1 = x

        如果这里求最大值却写 0.0f，所有负数都会被抹成 0 ——
        这就是 reducemax.cu 里专门做了三个对照实验的那个 bug。

  (b) 循环的三个部分

          for (int i = blockIdx.x * blockDim.x + tid;   // 起点：我的全局起始下标
               i < n;                                    // 条件：没越界就继续
               i += blockDim.x * gridDim.x)              // 步长：跨整个 grid 的宽度

      就是第 2.4 节讲的那个循环，不再重复。

  (c) 为什么 sum 要放寄存器，而不是直接写共享内存？

      因为**寄存器是最快的存储**，而且它私有 —— 每个线程各加各的，
      不需要同步。

      想象一下：如果每读一个元素就往共享内存加一次，那 256 个线程
      就会互相踩踏（都要往 sdata 上累加），而且每次都要栅栏，慢得离谱。

      正确做法就是：**先在自己的寄存器里默默加完，最后只往共享内存交一次账。**

  (d) 这一改动带来了什么

          每 block 搬的数据：      1 KiB   → 8 KiB    （搬得更多）
          block 数：               262144  → 32768    （少 8 倍）
          总栅栏次数：             786432  → 98304    （少 8 倍）
          每个线程手里的数据：     1 个    → 8 个      （有活干）

      **而「归约那段代码一行都没改」** —— 这就是 V2 设计上的漂亮之处：
      它不是重写算法，只是把「数据怎么进来」改了一下。

------------------------------------------------------------------------
3.5 把局部和交给共享内存
------------------------------------------------------------------------
      sdata[tid] = sum;
      __syncthreads();

  · sdata[tid] = sum;
      每个线程把自己寄存器里的 sum 放到共享内存的**第 tid 个**格子。

    ⚠ **下标必须是 tid，不能是 i** —— 因为 sdata 只有 256 格，
      而 i 可以是几千万。用 i 会立刻越界。
      （block 1 的 tid 0 会算出 i = 256，而 sdata[256] 已经出界了。）

    ⚠ **不需要再写 (i < n) ? ... : 0.0f** —— 因为循环没走到的线程，
      sum 就是单位元 0.0f，天然无害。

  · __syncthreads(); 是一道**栅栏**：

        T0  : ──写入──┃ 等 ┃──── 读取 ────
        T1  : ──写入──┃ 等 ┃──── 读取 ────
        ...            ↑
        T255: ──写入──┃ 等 ┃──── 读取 ────
                所有线程都到达这里，才放行

    **为什么不能省？** 因为下一步 T0 要去读 sdata[128]（那是 T128 写的）。
    如果没有栅栏，T0 可能在 T128 还没写之前就读了 → 读到垃圾值。

------------------------------------------------------------------------
3.6 【归约的核心】树形归约
------------------------------------------------------------------------
      for (int s = blockDim.x >> 1; s > 32; s >>= 1)
      {
          if (tid < s) sdata[tid] += sdata[tid + s];
          __syncthreads();
      }

  (a) >> 1 是什么？

      右移一位 = 除以 2。
      blockDim.x >> 1 = 128，而 s >>= 1 就是 s = s / 2。

  (b) 用 blockSize = 256 走一遍

      初始：sdata[0..255] 里是 256 个线程的局部和。

        s = 128 ：T0..T127 干活，sdata[0..127] += sdata[128..255]
                  结果：sdata[0..127] 变成 128 个数，每个是原来 2 个的和
        s = 64  ：T0..T63  干活，sdata[0..63]  += sdata[64..127]
                  结果：64 个数
        s = 32  →  32 > 32 为假，循环退出

      ⚠ **退出时还剩 64 个数**（sdata[0..63]）——
        这一段交给下面那个 if (tid < 32) 处理。

      画成图：

          下标   0    1    2    3   ...  127  128  ...  255
                1    1    1    1         1    1         1
                 └────┴────┴────┴─────────┘    ↑
          s=128    T0..T127：sdata[tid] += sdata[tid + 128]
                 ┌──┐ ┌──┐ ┌──┐ ...
                 │2 │ │2 │ │2 │              ← 128 个数
                 └──┘ └──┘ └──┘
          s=64     T0..T63：sdata[tid] += sdata[tid + 64]
                 ...

      **每一轮，存活的数字个数减半。** 8 轮之后 256 → 1。
      这就是「树形归约」，复杂度从 O(n) 变成 O(log n)。

  (c) 为什么用 tid < s 而不是别的写法？

      因为这样**前 s 个线程干的活是连续的**：

        · 一个 warp（32 个 lane）内的线程要么一起干活、要么一起歇着
          → **不发散**（divergence）
        · T0 读 sdata[0]，T1 读 sdata[1]…… 落在**不同的 bank**
          → **没有 bank conflict**

      （这两点在 reducesum.cu 的注释块里展开了，这里只给结论。）

  (d) ⚠ 栅栏为什么必须写在 if 外面？

          if (tid < s) {
              sdata[tid] += sdata[tid + s];
              __syncthreads();          // ❌ 绝对不能这样写
          }

      s = 128 那一轮，只有 T0~T127 会执行到这句栅栏，
      **T128~T255 永远到不了**。而栅栏的语义是「所有线程都必须到达」
      → 未定义行为，实际表现通常是**死锁**（程序卡住不动）。

      **口诀：__syncthreads() 永远写在条件分支外面。**

------------------------------------------------------------------------
3.7 收尾：展开最后一个 warp
------------------------------------------------------------------------
      if (tid < 32)
      {
          volatile float* v = sdata;
          v[tid] += v[tid + 32];
          v[tid] += v[tid + 16];
          v[tid] += v[tid +  8];
          v[tid] += v[tid +  4];
          v[tid] += v[tid +  2];
          v[tid] += v[tid +  1];
      }

  从主循环退出时 sdata[0..63] 还有 64 个数，这 6 行把它合成 1 个。

  (a) 为什么这里可以不要 __syncthreads()？

      因为干活的是 tid < 32，也就是**第 0 号 warp 的 32 个 lane**。
      而一个 warp 的 32 个 lane 是硬件调度的最小单位，
      **天然同时执行同一条指令** —— 跑到 v[tid] += v[tid+16] 时，
      32 个 lane 是一起跑的，不需要额外同步。

          主循环里：T0..T127 干活 → 横跨 4 个 warp → 必须栅栏
                    ┌─warp0─┐┌─warp1─┐┌─warp2─┐┌─warp3─┐

          最后一步：T0..T31 干活 → 只有 1 个 warp → 天然同步 ✅
                    ┌─warp0─┐

      省掉了 6 次栅栏。

  (b) volatile 是干什么的？

      **一句话：告诉编译器「别把这个值缓存到寄存器里，
        每次都老老实实去共享内存读」。**

      为什么需要？因为编译器看不到「别的线程在改这块共享内存」，它会想：

          「v[tid] 是我自己刚写过的，别人又不可能改，
            我缓存到寄存器里省几次内存访问」

      于是优化之后就读到了过期值。加上 volatile 就禁止了这个优化。

  (c) 6 行分别对应什么

          语句                      等价于主循环里   效果
          ----------------------    --------------   --------
          v[tid] += v[tid + 32]     s = 32           64 → 32
          v[tid] += v[tid + 16]     s = 16           32 → 16
          v[tid] += v[tid +  8]     s = 8            16 → 8
          v[tid] += v[tid +  4]     s = 4            8  → 4
          v[tid] += v[tid +  2]     s = 2            4  → 2
          v[tid] += v[tid +  1]     s = 1            2  → 1  ✅

------------------------------------------------------------------------
3.8 交出部分和
------------------------------------------------------------------------
      if (tid == 0) out[blockIdx.x] = sdata[0];

  · 只有 T0 去写（结果只有一个，不能让 256 个线程都写）
  · 写到 out[blockIdx.x] —— **每个 block 占一个格子**，互不重叠
  · 不需要再加栅栏：sdata[0] 正好是 T0 自己刚写完的，
    同一个线程读写天然有序


