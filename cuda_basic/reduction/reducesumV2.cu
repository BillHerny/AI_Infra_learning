第 6 步　自测题（能全答出来才算真懂）
========================================================================

  1. sdata[tid] = sum; 这一行，为什么下标用 tid 而不是 i？

  2. 为什么 sdata[tid] = sum; 前面不需要 (i < n) ? ... : 0.0f
     这样的边界判断？

  3. for (int s = blockDim.x >> 1; s > 32; s >>= 1) 里，
     为什么条件是 > 32 而不是 > 0？

  4. 如果把 elemsPerThread 设成 1，V2 和 V1 的性能应该一样还是不一样？
     为什么？

  5. float sum = 0.0f; 这个初值，如果我们要算的是**最大值**，
     应该改成什么？

  ── 参考答案 ──
  1. sdata 只有 blockDim 长（256 格），而 i 可以到几千万；用 i 会越界。
  2. 因为没进循环的线程 sum 就是单位元 0.0f，混进加法里无害。
  3. 因为 s > 32 之后，存活的数据已经落在一个 warp 内部，
     warp 天然同步，不需要栅栏 —— 剩下的 6 步手工展开更划算。
  4. 一样。elemsPerThread = 1 时 grid = 262144，grid-stride 只跑一轮，
     行为完全退化成 V1。
  5. 改成 -FLT_MAX（或用 FLT_MAX 按运算取反），
     因为 0 对 max 不是单位元，会把所有负数抹成 0。
     这就是 reducemax.cu 里那个「单位元 bug」的由来。

