------------------------------------------------------------------------
4.2 【核心】grid 的算法
------------------------------------------------------------------------
      int grid    = (n + blockSize - 1) / blockSize;                  // 上限
      int gridCap = (n + blockSize * elemsPerThread - 1) /
                    (blockSize * elemsPerThread);                     // 封顶值
      if (grid > gridCap) grid = gridCap;
      if (grid < 1) grid = 1;

  我们把 (x + d - 1) / d 叫「**向上取整除法**」
  （因为整数除法是向下取整的，先加 d-1 再除，效果就是向上取整）。

  用默认值代入：

      grid    = (67108864 + 255) / 256   = 262144   ← 一线程一元素需要这么多
      gridCap = (67108864 + 2047) / 2048 = 32768    ← 每线程 8 个只需要这么多
      262144 > 32768  →  grid = 32768

  **一句话：先算出「一个线程一个元素」需要多少 block（这是上限），
    再按「每线程 8 个」把它缩小 8 倍。**

  缩小后会发生什么？线程变少了，但元素数没变，
  所以**每个线程自然就得多干几个** —— 而多干的部分由 kernel 里的
  grid-stride 循环吃掉。

  ⚠ **这是 V2 的「总开关」**：如果 elemsPerThread = 1，
    那 grid = 262144，V2 就退化成 V1 了（也就拿不到任何加速）。
    正好可以当实验：
        ./build/bin/reducesumV2 $((1<<26)) 256 1

