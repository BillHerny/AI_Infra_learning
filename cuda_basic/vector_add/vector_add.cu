第 2 章　常见疑问 FAQ
========================================================================

问 1：kernel 里没有 return，结果是怎么送回来的？
答：靠指针参数写出去的。
    参数 float* c 指向显存里的一块空间，
    kernel 里每个线程算完就执行 c[i] = ...。
    所以「输入靠参数传进去，输出靠写内存传出来」。

问 2：为什么 cudaMalloc 要写 &d_a，而不是 d_a？
答：因为 cudaMalloc 的任务是「分配一块显存，然后把地址写进你这个变量」。
    要想让它修改一个变量，你就得把这个变量的地址交给它 —— 也就是 &d_a。
    （相比之下，malloc 是直接把地址「返回」给你，所以不用传地址进去。）

问 3：grid 为什么要写成 (n + block - 1) / block ？
答：因为整数除法会向下取整。
    直接写 n / block，最后不满一组的元素就会漏掉没人处理。
    先加 (block - 1) 再除，效果就等于「向上取整」。
    多出来的那些线程不会闯祸，kernel 里的 i < n 会把它们拦住。

问 4：为什么计时不把 cudaMemcpy 也算进去？
答：因为我们测的是「kernel 快不快」，不是「数据传输快不快」。
    混在一起会把 kernel 的真实性能掩盖掉。
    如果想知道传输有多慢，得单独给 memcpy 计时。

问 5：CPU 版那么慢，为什么还要写？
答：它不参与性能测试，只当「标准答案」用。
    没有它，你根本不知道 GPU 算得对不对。

问 6：blockDim.x * gridDim.x 到底等于多少？
答：等于「这个 grid 里一共有多少个线程」，
    也就是「跑一轮最多能覆盖多少个元素」。
    本例 = 256 × 262144 = 67,108,864 = N，正好一轮覆盖完。

