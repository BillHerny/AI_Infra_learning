#include <cstdio>
#include <cstdlib>
#include <cmath>
#include <cuda_runtime.h>

// =========CUDA CHECK========
#define CUDA_CHECK(call)                                          \
    do{                                                           \
        cudaError_t err = (call);                                 \
        if(err != cudaSuccess){                                   \
            fprintf(stderr, "CUDA error %s:%d: %s\n",             \
                   __FILE__, __LINE__, cudaGetErrorString(err));  \
            exit(EXIT_FAILURE);                                   \
        }                                                          \
    }while(0)

// ============KERNEL :c[i] = a[i] + b[i] ============
// __restrict__  tell the compiler that the pointer is not aliased
__global__ void vectorADD(const float* __restrict__ a,
                          const float* __restrict__ b,
                          float* __restrict__ c,
                          int n)
    {
    int idx = blockIdx.x * blockDim.x + threadIdx.x;

    // grid-stride loop: 每个线程跨整个 grid 处理多个元素
    // grid大小与N解耦，极大的N也能安全处理
    for(int i = idx; i < n; i += blockDim.x * gridDim.x){
        c[i] = a[i] + b[i];
        }
    }

// =========CPU 参考 ==========
void vectorADD_CPU(const float* a, const float* b, float* c, int n){
    for(int i = 0; i < n; i++) c[i] = a[i] + b[i];}


int main(int argc, char** argv)
{
    int n = (argc > 1) ? atoi(argv[1]) : (1 << 26);
    //如果命令行传了参数，就用命令行传的参数，如果没有就用默认值 
    int thread_per_block = (argc > 2) ? atoi(argv[2]) : 256;

    size_t bytes = (size_t)n * sizeof(float);
    //强制转型n为 size_t 类型， size_t容量大
    

    // allocate memory on host and initialize
    float* h_a = (float*)malloc(bytes);
    float* h_b = (float*)malloc(bytes);
    float* h_c = (float*)malloc(bytes); //memorize GPU result
    float* ref = (float*)malloc(bytes); //memorize CPU result
    for(int i = 0; i < n; i++) { h_a[i] = 1.0f; h_b[i] = 2.0f; }

    // allocate memory on device
    float *d_a, *d_b, *d_c;
    CUDA_CHECK(cudaMalloc(&d_a, bytes));
    CUDA_CHECK(cudaMalloc(&d_b, bytes));
    CUDA_CHECK(cudaMalloc(&d_c, bytes));

    CUDA_CHECK(cudaMemcpy(d_a, h_a, bytes, cudaMemcpyHostToDevice));
    CUDA_CHECK(cudaMemcpy(d_b, h_b, bytes, cudaMemcpyHostToDevice));

    // =========start ==========
    int grid = (n + thread_per_block - 1) / thread_per_block; //向上取整
    printf("N = %d, number of blocks = %d,thread_per_block = %d, each array = %.1f MiB\n",
           n, grid,thread_per_block, bytes / 1024.0 / 1024.0);
    // ==========warm-up ,let GPU time/cache get ready=========
    vectorADD<<<grid, thread_per_block>>>(d_a, d_b, d_c, n);

    /*kernel 启动失败不会通过返回值报错，必须主动查询。
    常见失败原因：block 超过 1024、grid 超过上限。*/
    CUDA_CHECK(cudaGetLastError());
      /*等 GPU 全部干完（阻塞 CPU）。
      为什么 warm-up 要等它？ 两个目的：
      确保第一次运行真正完成，让 GPU 提频、把指令缓存加载好；
      把"第一次启动的额外开销"挡在正式计时之外。*/
    CUDA_CHECK(cudaDeviceSynchronize());

    // ==========measure time ==========
    cudaEvent_t start, stop;
    CUDA_CHECK(cudaEventCreate(&start));
    CUDA_CHECK(cudaEventCreate(&stop));
    
    const int iters = 20;
    float best_ms = 1e30f;
    for (int i = 0; i < iters; i++) {
        CUDA_CHECK(cudaEventRecord(start));
        vectorADD<<<grid, thread_per_block>>>(d_a, d_b, d_c, n);
        CUDA_CHECK(cudaEventRecord(stop));
        CUDA_CHECK(cudaEventSynchronize(stop));

        float ms = 0.0f;
        CUDA_CHECK(cudaEventElapsedTime(&ms, start, stop));
        if (ms < best_ms) best_ms = ms; // 取最小值，减少节流干扰
    }

    CUDA_CHECK(cudaMemcpy(h_c, d_c, bytes, cudaMemcpyDeviceToHost));
    vectorADD_CPU(h_a, h_b, ref, n);

    int bad = 0;
    for (int i = 0; i < n; i++) {
        if (fabsf(h_c[i] - ref[i]) > 1e-5f) {
            if (bad <5)
                printf(" mismatch @ %d: gpu = %f cpu = %f\n", i, h_c[i], ref[i]);
            bad++;
        }
    }

    printf("verify: %s (%d mismatches)\n", bad ? "FAIL" : "PASS", bad);

    // =========calculate bandwidth ==========
    double gb = 3.0 * bytes / 1e9;
    double bw = gb / (best_ms / 1e3);
    printf("best time           = %.3f ms\n", best_ms);
    printf("effective bandwidth = %.1f GB/s\n", bw);

    // =========free memory ==========
    free(h_a); free(h_b); free(h_c); free(ref);
    CUDA_CHECK(cudaFree(d_a));
    CUDA_CHECK(cudaFree(d_b));
    CUDA_CHECK(cudaFree(d_c));
    CUDA_CHECK(cudaEventDestroy(start));
    CUDA_CHECK(cudaEventDestroy(stop));
    return 0;

}

