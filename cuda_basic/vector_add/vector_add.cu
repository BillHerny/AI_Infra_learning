专题 4　逐块解释
------------------------------------------------------------------------

  【1】#define CUDA_CHECK(call)   （行尾还有一个反斜杠）

      · #define     → 「我要定义一个宏」
      · CUDA_CHECK   → 宏的名字
      · (call)       → 宏的参数。注意：它和函数参数长得像，
                       但本质是「文本占位符」——替换时用你传进来的东西填进去。
      · 行尾反斜杠   → 叫「续行符」，意思是「这一行还没写完，下一行也算我的」。

  【2】为什么每一行末尾都要有那个反斜杠？

      因为 #define 默认只管一行！

      如果你把反斜杠去掉，就变成：

         #define CUDA_CHECK(call)          // 宏体是空的！
             do{                            // ← 这行变成一条独立的、没头没脑的语句
                 cudaError_t err = (call);

      编译器看到第 8 行就会报：
         error: expected a declaration
      然后跟着二十多个「被带崩」的错误，全都指向别的地方。

      ⚠ 这就是你们之前踩过的坑：24 个报错，真正的原因只有一个。

      ⚠ 还有一个更隐蔽的点：反斜杠后面「连空格都不能有」。
        因为它必须是该行的最后一个字符，多一个空格它就失效了。

  【3】do { ... } while(0) —— 看起来像循环，其实只为「打包」

      它先执行一遍循环体，再看条件；而条件被写死成 0（假），
      所以循环永远不会回头 —— 它只执行一次。

      那为什么还要这么大费周章？为了把「好几行代码」包成「一条语句」。

      反例：假设宏体没有包起来，写成

         #define F(x)  第一个动作(x); 第二个动作(x)

      那么当你写

         if (某条件)
             F(x);          // 你只想条件成立时才执行
         else
             别的动作;

      替换之后会变成

         if (某条件)
             第一个动作(x);  第二个动作(x);    // ← 到这里 if 就结束了
         else                                 // ← 编译器：这个 else 是谁的？
             别的动作;

      → 编译错误。

      用 do { ... } while(0) 包起来之后，整体就「像一条语句」一样安全：

         if (某条件)
             do { ... } while(0);
         else
             别的动作;                        // 没问题

  【4】cudaError_t err = (call);

      · cudaError_t  → CUDA 定义的「错误码」类型，这是个遍历，本质是个整数；
      · cudaSuccess  → 表示「成功」的那个值（等于 0）；
      · 所以 err != cudaSuccess 的意思就是「没成功，出错了」。
      · err 这个变量是在 do{ } 里面新声明的，
        所以每次调用都用一个新的，互相不会打架。

  【4.1】为什么写 (call) 而不是直接写 call？

      先澄清一个容易误会的地方：
      (call) 里的括号不是「函数调用」的括号，只是普通的分组括号。
      替换之后实际长这样：

         cudaError_t err = (cudaMalloc(&d_a, bytes));
                           ↑                        ↑  这两个是一对

      问：能不能去掉括号，直接写成 cudaError_t err = call; ？
      答：就这个文件里现有的所有调用来说，能。
          因为这些实参本身都已经是「一个完整的函数调用」，
          外面再套一层括号不改变任何东西。
          也就是说，这里的括号是「保险」，不是「必需」。

      那为什么还要加？因为宏的参数是「原样文本」，可能是任意表达式。
      下面两种情况，不加括号就会出错。

      情况一：逗号表达式

         CUDA_CHECK((foo(), bar()))
           有括号 → (foo(), bar())    先跑 foo()，err 取 bar() 的值
           没括号 → err = foo(), bar() 被解析成 (err = foo()), bar()

      情况二：运算符优先级（更经典的坑）

         #define DOUBLE(x) x * 2
         DOUBLE(1 + 2)        替换成 1 + 2 * 2 = 5        你以为要 6

         #define DOUBLE(x) ((x) * 2)
         DOUBLE(1 + 2)        替换成 ((1 + 2) * 2) = 6    这才是对的

         整个宏体也要一起包起来，否则：
         #define ADD(a, b) a + b
         2 * ADD(1, 2)        替换成 2 * 1 + 2 = 4        你以为要 6

      宏的两层保护（可以背下来）：
        · 表达式级：宏体里出现的每个参数都加括号
                    防的是运算符优先级、逗号表达式把语义搞乱
        · 语句级：整体用 do { ... } while(0) 包起来
                    防的是在 if / else 里展开时结构被撑破

      你这个宏两层都做了 —— 看着啰嗦，其实是很规范的写法。

      一条可以背下来的规则：
        写宏时 —— 参数一律加括号，整体一律包起来。
        宁可多写几个括号，也不要让「文本替换」改变原意。

      想亲手验证：把第 9 行的 (call) 改成 call，重新编译运行，
      结果完全一样（verify: PASS，带宽不变）。
      这正好说明此处括号是「保险」而非「必需」。

  【4.2】call 到底是「形参」还是「实参」？和函数的参数一样吗？

      一句话回答：结构上和函数一模一样，但「传的东西」不同。

      术语对照：

        对比项         函数                          宏
        ------------   ---------------------------   -----------------------------
        占位符叫       形参（formal parameter）      形参（macro parameter）
        就是这里       void f(int x) 里的 x          #define CUDA_CHECK(call) 里的 call
        调用时传的     实参（argument）              实参（argument）
        本文件的实参   （无）                        cudaMalloc(&d_a, bytes)

      所以：(call) 确实就是「形参」，
            你写的 cudaMalloc(&d_a, bytes) 就是传给它的「实参」。

      但有一个本质区别 —— 函数传「值」，宏传「文本」：

        · 函数：实参先「求值」，把算好的值传进去，而且类型要匹配。

            int square(int x) { return x * x; }
            square(2 + 3);     先把 2+3 算成 5，再把 5 传进去   → 25

        · 宏：实参「不求值」，原封不动当一段文字贴进去。

            #define SQUARE(x) ((x)*(x))
            SQUARE(2 + 3);     直接贴成 ((2+3)*(2+3))          → 25
            （这里能得到 25，是因为宏体里自己写了括号在保护）

      三个角度的差别：

        · 传的是什么：函数传「求值后的值」；宏传「未经处理的文字」
        · 类型检查：  函数有（传错类型会报错）；宏没有（宏根本不关心类型）
        · 副作用：    函数只发生一次；宏可能发生多次  ← 最容易踩的坑

      副作用例子（务必看懂）：

        #define SQUARE(x) ((x)*(x))

        int a = 5;
        int r = SQUARE(a++);     被替换成 ((a++)*(a++))

        a++ 出现了两次！后果：
          · a 被加了 2 次，最后 a = 7
          · r 也不是你以为的 25

        换成函数就绝不会这样：函数会先把 a++ 算成 5，
        再把「值 5」传进去，所以 a 只加一次。

        这就是「宏是文本替换」带来的直接后果。

      回到你的宏：

        你传进去的 cudaMalloc(&d_a, bytes) 只会被「用一次」，
        所以不存在上面那种副作用问题。
        但如果哪天你写成 CUDA_CHECK(x++)，就要小心了。

      顺带一个小知识点：实参里的逗号会不会被误拆成两个参数？

        CUDA_CHECK(cudaMalloc(&d_a, bytes));
        这个逗号在 cudaMalloc( 的括号里面，
        预处理器会记录「括号深度」，深度不为 0 就不算参数分隔符，
        所以它不会被拆开，放心。

        （但如果写成 CUDA_CHECK(a, b) 这种「顶层逗号」，
        就会被当成两个实参，而宏只声明了一个形参 → 报错。）

  【5】fprintf(stderr, "CUDA error %s:%d: %s\n", __FILE__, __LINE__, cudaGetErrorString(err));

      这一行的目的：把「哪里错了、错什么」打印出来。有三块料：

        __FILE__                 编译器自动填上「当前文件名」
        __LINE__                 编译器自动填上「出错的第几行」
        cudaGetErrorString(err)  把错误码翻译成人看得懂的描述

      所以实际打印出来长这样：

        CUDA error /home/.../vector_add/vector_add.cu:57: out of memory

      ⚠ __FILE__ 和 __LINE__ 很聪明：它们填的是「宏被调用的那一行」，
        不是宏定义所在的那一行。这正是「用宏而不用函数」的原因之一
        （写成函数的话，只能拿到函数内部的行号，等于白搭）。

      · 为什么用 fprintf(stderr, ...) 而不是 printf(...)？
        stderr 是「标准错误」这个输出通道。
        好处：即使你把正常输出重定向到文件（命令后面写 > out.txt），
        错误信息依然会打在屏幕上，不会被吞掉。
        （下面【5.1】把这件事彻底讲透。）

  【5.1】fprintf / printf / cout 到底该怎么选？

      一句话：printf 和 fprintf 的区别不在「打印什么」，而在「往哪个通道打印」。

      (1) printf 其实就是 fprintf 的特例

          C 语言预定义了三个标准通道（流）：

            通道        名字      编号    用途
            --------    -------   ----    --------------
            标准输入    stdin     0       键盘输入
            标准输出    stdout    1       正常结果
            标准错误    stderr    2       错误信息

          而：
            printf("...", ...);           等价于 fprintf(stdout, "...", ...);
            fprintf(stderr, "...", ...);  明确指定：写到「错误通道」

          所以 printf 只能写 stdout，它没法写 stderr
          —— 这就是这里非用 fprintf 不可的唯一原因。

      (2) 为什么错误非要走 stderr？

          因为 stdout 和 stderr 是两条独立的「水管」，可以分别重定向。

          例如你这样运行：
            ./build/bin/vector_add > out.txt

            · N = ...、verify: PASS、bandwidth 这些正常结果 → 全进 out.txt
            · 万一中途 CUDA 出错，错误信息依然打在屏幕上
              （因为它在 stderr，不受 > 影响）

          如果这里用的是 printf，错误信息就一起被导进文件了，
          终端上什么都看不到，程序都退出了你还不知道发生了什么。

          重定向速查：
            > out.txt          正常输出存文件，错误留在屏幕
            > out.txt 2>&1     两个都存进文件
            > /dev/null        只想看错误
            2> /dev/null       只把错误丢掉
          （2> 里的 2 就是 stderr 的编号）

      (3) 还有一个隐性好处：缓冲

          · stdout 在输出到「文件」时是块缓冲（攒够一大块才写出去）；
          · stderr 默认无缓冲，立刻写出去。

          如果程序崩溃了，stdout 缓冲区里还没写出去的内容会直接丢掉；
          走 stderr 的错误信息则早就写出去了 ——
          那正是崩溃现场最需要的线索。

      (4) 为什么不用 cout / cerr？

          ① 最实际的理由：kernel 里根本用不了 cout。

             __global__ void myKernel() {
                 printf("hello from GPU\n");    // CUDA 支持（设备端 printf）
                 // std::cout << "...";         // 完全不行，设备端不支持 iostream
             }

             为了让主机端和设备端风格统一，CUDA 代码几乎清一色用 C 风格 printf。

          ② 语法冗长、格式化麻烦：

             C 风格一行搞定：
               fprintf(stderr, "CUDA error %s:%d: %s\n", __FILE__, __LINE__, ...);

             C++ 风格要 include <iostream>，还要拼一串 << ：
               std::cerr << "CUDA error " << __FILE__ << ":" << __LINE__ << ...;

             而且 %s / %d / %.1f 这种格式串，在控制小数位数和对齐时方便得多
             （本文件里的 %.1f MiB、%.3f ms 就是这么用的）。

          ③ 混用两套 IO 可能顺序错乱：

             printf（C 风格）和 cout（C++ 风格）是两套独立的缓冲体系，
             混着用，输出的先后顺序可能和你写的不一致。

      (5) 对比一览

          写法                     写到哪   设备端能用   适合
          ----------------------   -------  ----------   ----------------
          printf(...)              stdout   可以         正常结果
          fprintf(stdout, ...)     stdout   可以         同上（显式写法）
          fprintf(stderr, ...)     stderr   可以         错误信息（本代码）
          cout << ...              stdout   不行         C++ 程序
          cerr << ...              stderr   不行         C++ 程序

      (6) 回到你的代码：这是刻意分开的

          printf("N = %d, ...");                           // 正常结果 → stdout
          printf("verify: %s ...");                        // 正常结果 → stdout
          printf("effective bandwidth = ...");             // 正常结果 → stdout

          fprintf(stderr, "CUDA error %s:%d: %s\n", ...);  // 错误 → stderr（只此一处）

          正常走 stdout，出错走 stderr —— 这是很规范的写法。

      (7) 动手验证（配合专题 5 一起做）

          第一步：正常跑一遍，把正常输出导进文件
            ./build/bin/vector_add > out.txt
            cat out.txt        # 里面只有 N、verify、带宽

          第二步：用专题 5 的办法故意制造错误（临时申请 1000 GB 显存），然后
            ./build/bin/vector_add > out.txt     # 报错信息依然显示在屏幕上！

          你会亲眼看到：正常输出进了文件，错误信息还留在屏幕
          —— 这就是 stderr 存在的意义。

  【5.2】__FILE__ 里的双下划线是什么意思？

      一句话：双下划线不是「特殊语法」，而是「命名约定」——
      它表示这个名字是「编译器 / 标准库专用的」，普通程序员不该用。

      (1) __FILE__ 是什么？

          它是一个「预定义宏（predefined macro）」——
          编译器在编译时自动就把它定义好了，你从来没写过 #define __FILE__。

          编译器扫到它时，会把它替换成「当前源文件的路径字符串」：

            printf("%s\n", __FILE__);
            输出： /home/.../cuda_basic/vector_add/vector_add.cu

          同类还有几个，都是编译器送的：
            预定义宏     替换成              类型
            ----------   -----------------   --------
            __FILE__     当前源文件路径       字符串
            __LINE__     当前行号             整数
            __DATE__     编译日期             字符串
            __TIME__     编译时间             字符串
            __func__     当前函数名           字符串

          正因为有 __FILE__ 和 __LINE__，
          上面那句 fprintf 才能打印出「哪个文件、哪一行」。

      (2) 为什么偏偏用双下划线？—— 保留名规则

          C / C++ 标准规定了几类「保留标识符（reserved identifier）」：

            名字长什么样                              谁能用
            ---------------------------------------   ---------------------
            任何位置含双下划线（__FILE__、my__var）   只有实现方（保留）
            下划线 + 大写字母开头（_Foo）             保留
            下划线开头（全局作用域，_foo）            保留

          原因很简单：防止撞名。
            编译器、标准库、CUDA 运行时内部要定义一大堆名字。
            如果它们用 FILE、LINE 这种普通名字，你写的代码很可能也有个 FILE，
            那就冲突了。于是约定：双下划线包围的名字全归我，用户别碰。

      (3) 你这份代码里就藏着几个

            __FILE__       预定义宏（编译器提供）
            __LINE__       预定义宏（编译器提供）
            __global__     CUDA 关键字
            __restrict__   CUDA 关键字

          CUDA 把它们写成这个样子，正是为了不和你的代码撞名 ——
          你自己写一个叫 global 的变量也完全没事。

          其他常见的同类：
            · 标准库预定义宏：__STDC__、__cplusplus
            · 编译器扩展：    __attribute__（GCC/Clang）、__declspec（MSVC）、__int64
            · CUDA 其他：     __device__、__shared__、__syncthreads()、__constant__

      (4) 给自己起名时的铁律

            绝对不要用双下划线！
              ✗  int __count;
              ✗  void __init();
              ✗  #define __MY_MAX 100

            用普通名字就好：
              ✓  int count;)
              ✓  void init(;
              ✓  #define MY_MAX 100

          为什么？用了双下划线，这一次编译可能没问题，
          但换个编译器或升级版本，就可能突然报出一堆莫名其妙的冲突，
          而且错误信息会指向你完全看不懂的地方。

          （顺便：社区里把 __ 读作 dunder，是 double underscore 的缩写。）

      (5) 澄清一个容易混淆的点：双下划线不是「关键字」

          编译器并不「解析」那两道下划线。
          对编译器来说，__FILE__ 就是一个「普通的标识符」，
          只不过这个名字被预留下来、而且预处理器已经给它赋好了值。

            名字                     性质
            ---------------------   ---------------------------------------
            if / for / return       关键字（keyword），语法层面有特殊含义
            __FILE__                预定义宏（名字被保留 + 值预先定义好）
            __global__              CUDA 的关键字（nvcc 眼中），用了同样的约定

      (6) 动手看看

          临时在 main 开头加几句：

            printf("file = %s\n", __FILE__);
            printf("line = %d\n", __LINE__);
            printf("date = %s, time = %s\n", __DATE__, __TIME__);

          编译运行，会看到类似：

            file = /home/.../vector_add/vector_add.cu
            line = 38
            date = Oct  6 2026, time = 21:33:07

          再把这几行上下移动一行，__LINE__ 的值就会跟着变 ——
          这就证明它是「编译时按位置填进去的」，不是运行时算出来的。

          看完记得把这几行删掉。

  【6】exit(EXIT_FAILURE);

      · EXIT_FAILURE 是 cstdlib 里定义好的常量，值是 1，表示「失败退出」；
      · exit(...) 会立刻结束整个程序。
      · 为什么这么狠？GPU 都出错了，继续往下跑只会产生更多误导性的结果，
        不如当场停下，让你第一时间看到真实的失败点。

  【7】第 14～15 行：}  和  }while(0)

      给 do{ 收尾。
      注意：宏定义里「最后不带分号」，分号由调用处提供
      （你写 CUDA_CHECK(x); 的那个分号）。
      这样展开后才是一条完整合法的语句。

