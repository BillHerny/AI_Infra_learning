  ────────────────────────────────────────────────────────────────
  【第 63～64 行】给 kernel 配置「要开多少个 block」
  ────────────────────────────────────────────────────────────────
      int grid = (n + block - 1) / block;

    这是「向上取整除法（ceiling division）」的经典写法。

    · 想要的是 ceil(n / block)（向上取整），
      但 C 的整数除法天生「向下取整」，
      所以先加上 (block - 1)，再整除 —— 就变成向上取整了。

    · 用具体数字走一遍（n = 10、block = 4）：
          (10 + 4 - 1) / 4 = 13 / 4 = 3   → 开 3 个 block
          3 个 block × 4 线程 = 12 个线程，能覆盖 10 个元素 ✅

    · 如果偷懒直接写 n / block：
          10 / 4 = 2  → 只覆盖 8 个元素，后 2 个没人算 ❌

    · 多出来的 2 个线程（12 − 10 = 2）怎么办？
      由 kernel 里那句 i < n 拦住：它们的 idx 是 10、11，
      一进循环就发现 i >= n，直接退出，不会越界写内存。
      这叫「边界保护（boundary check）」。

  ────────────────────────────────────────────────────────────────
  【第 66～67 行】warm-up：先空跑一遍
  ────────────────────────────────────────────────────────────────
      vectorADD<<<grid, block>>>(d_a, d_b, d_c, n);

    · 这就是「启动 kernel」的语法：
          函数名 <<< 配置 >>> ( 参数... )
      <<< 和 >>> 是 CUDA 的扩展语法，只有 nvcc 能编译，普通的 C++ 编译器不认识。

    · <<< >>> 里放两个启动配置：
          第一个 grid  ：开多少个 block
          第二个 block ：每个 block 多少线程
      所以这一行的意思是：
          开 grid 个 block、每个 block 里 block 个线程，一起来跑 vectorADD。

    · 这一行是「异步（asynchronous）」的：
      CPU 发出命令后立刻往下走，不会等 GPU 算完。
      这正是后面必须用 cudaEvent 计时的根本原因 ——
      CPU 侧根本没有「kernel 花了多久」这个信息。

