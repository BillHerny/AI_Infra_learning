  ────────────────────────────────────────────────────────────────
  【第 43 行】size_t bytes = (size_t)n * sizeof(float);
  ────────────────────────────────────────────────────────────────
  目的：算出「一个数组占多少字节」。

    · size_t bytes    → size_t 是「专门用来装大小 / 个数」的无符号整数类型，
                        能装下很大的数（64 位下最大约 1.8e19）。
    · (size_t)n       → 把 n 临时转换成 size_t 类型（强制类型转换）。
    · sizeof(float)   → 取 float 占几个字节 = 4。
    · 整体            → bytes = n × 4。

  为什么必须写 (size_t)n？看这个推演：
      如果 n 保持 int：
          int × int = int   →  大 n 时会「溢出」，结果变成负数！
      如果先用 (size_t) 转一下：
          size_t × int = size_t  →  不会溢出 ✅

  int 最大约 21 亿。本例 n = 67,108,864，乘 4 还安全；
  但如果你把 N 设成 10 亿，n * 4 就已经越过 int 上限，程序直接崩。
  「先转大类型再乘」不是可选项，是硬功夫。

  本例：bytes = 67,108,864 × 4 = 268,435,456 字节 = 256 MiB。

