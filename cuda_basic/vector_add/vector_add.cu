------------------------------------------------------------------------
专题 1　宏（macro）是什么？
------------------------------------------------------------------------
   宏 = 编译正式开始之前，由「预处理器」做的一次「查找替换」。

   你可以把它理解成编辑器里的「查找替换」功能，只是由编译器自动完成：

     #define PI 3.14              // 定义：以后看到 PI，就换成 3.14
     float area = PI * r * r;     // 编译器实际看到的是 3.14 * r * r

   带参数的宏也一样：

     #define SQUARE(x) ((x)*(x))
     int a = SQUARE(5);           // 被换成 ((5)*(5))
     int b = SQUARE(2+3);         // 被换成 ((2+3)*(2+3))

   一句话：宏不是函数，它只是「把文字换掉」，然后再交给编译器去编译。

------------------------------------------------------------------------
专题 2　这个宏是干什么用的？
------------------------------------------------------------------------
   一句话：每次调用 CUDA 的函数，它都帮我们检查「有没有出错」；
           出错就打印「出错位置 + 原因」，然后结束程序。

   为什么必须检查？
     因为 CUDA 的函数不会「抛异常」，它们只返回一个「错误码」（一个整数）。
     你不检查，出错也会悄无声息，后面就变成莫名其妙的崩溃或错误结果。

   如果没有这个宏，你就得在每个 CUDA 调用后面都重复写一遍检查代码：

     cudaError_t err = cudaMalloc(&d_a, bytes);
     if (err != cudaSuccess) { ...打印... ...退出... }

     err = cudaMemcpy(...);
     if (err != cudaSuccess) { ...又打印一遍... }

     err = cudaEventCreate(&start);
     if (err != cudaSuccess) { ...还要再写一遍... }

   你文件里调用了二三十次 CUDA 函数。
   宏的作用就是：把这段检查代码「写一次，反复用」。

------------------------------------------------------------------------
专题 3　把调用「展开」给你看（最关键的一步）
------------------------------------------------------------------------
   你实际写的那一句（第 56 行附近）是：

     CUDA_CHECK(cudaMalloc(&d_a, bytes));

   经过宏替换之后，编译器真正看到的代码是：

     do {
         cudaError_t err = (cudaMalloc(&d_a, bytes));
         if (err != cudaSuccess) {
             fprintf(stderr, "CUDA error %s:%d: %s\n",
                     __FILE__, __LINE__, cudaGetErrorString(err));
             exit(EXIT_FAILURE);
         }
     } while (0);

   看出来了吗？
     宏定义里的 call 这个「占位符」，被你的 cudaMalloc(&d_a, bytes) 填了进去，
     然后整段代码被塞到你写的那一行上。

   所以这个宏 = 「帮我调用这个函数 + 顺手检查它的返回值」。

