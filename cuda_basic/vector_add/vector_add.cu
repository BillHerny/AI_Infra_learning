第六部分：验证与统计（第 89～107 行）
========================================================================

  ────────────────────────────────────────────────────────────────
  【第 89 行】把 GPU 结果拷回主机
  ────────────────────────────────────────────────────────────────
      CUDA_CHECK(cudaMemcpy(h_c, d_c, bytes, cudaMemcpyDeviceToHost));

    · 方向反过来：device → host。
    · 四个参数对照：
          目标 h_c  ←  源 d_c   ←  字节数 bytes  ←  方向 DeviceToHost
    · 注意方向标记写反会怎样：
      cudaMemcpy 会返回错误码（invalid argument），CUDA_CHECK 会拦下来。
      这也是为什么每次 memcpy 都要包 CUDA_CHECK。
    · 这一步也是同步的，返回后 h_c 里就是完整结果。
    · 顺带注意：在第 89 行之前，h_c 里是 malloc 留下的随机值（垃圾）；
      这次 memcpy 是它「第一次被赋值」。

    ⚠ 必然会冒出来的疑问：「为什么不能直接比较 h_c[i] 和 d_c[i]？」
      → 见上方【专题 7】：CPU 根本读不到设备指针，强行读会 segfault。

  ────────────────────────────────────────────────────────────────
  【第 90 行】在 CPU 上算一遍参考结果
  ────────────────────────────────────────────────────────────────
      vectorADD_CPU(h_a, h_b, ref, n);

    · 输入仍是 h_a、h_b，输出写进 ref。
    · 为什么可以放心复用 h_a、h_b？
      它们从头到尾没被改动过（GPU 只在 d_a/d_b 上算），所以还是原始的 1.0 / 2.0。
    · 为什么要有这一步？
      这叫「对拍（cross-check）」：
      拿一个「逻辑简单、肯定正确」的实现当基准，去验证复杂的实现。
      这是所有 kernel 开发的第一道保险。

  ────────────────────────────────────────────────────────────────
  【第 92 行】int bad = 0;
  ────────────────────────────────────────────────────────────────
    · 记录「不一致的元素个数」。
    · 初值必须是 0，而且必须在循环「外面」声明，
      放进循环里的话每次都会被清零。

  ────────────────────────────────────────────────────────────────
  【第 93～99 行】对拍循环
  ────────────────────────────────────────────────────────────────
      for (int i = 0; i < n; i++) {
          if (fabsf(h_c[i] - ref[i]) > 1e-5f) {
              if (bad < 5)
                  printf(" mismatch @ %d: gpu = %f cpu = %f\n", i, h_c[i], ref[i]);
              bad++;
          }
      }

    · 逐层拆开读：
        for (int i = 0; i < n; i++)        逐个元素走一遍
        fabsf(h_c[i] - ref[i])             取「差值」的绝对值
        > 1e-5f                            偏差超过容差 → 判定为错
        1e-5f 就是 float 的容差（tolerance），约等于 0.00001

    ⚠ 坑 1：浮点数不能用 == 比较。
        GPU 与 CPU 的加法顺序、所用指令不同，结果可能有极小的偏差。
        例如数学上都是 3.0，一个算出 2.9999998，一个算出 3.0000002，
        用 == 判就「全是错」，但其实是完全正常的。
        所以必须用「容差比较」：|GPU − CPU| > 1e-5f 才算错。

    ⚠ 坑 2：为什么用 fabsf 而不是 fabs？
        fabsf 是「float 版」绝对值，fabs 是「double 版」。
        对 float 用 fabs 会先隐式升成 double、算完再降回来，多一次转换。
        函数名末尾的 f 和字面量 1.0f 的 f 是同一个意思。

    ⚠ 坑 3：if (bad < 5) 为什么只打印前 5 条？
        如果全部算错，就是 6700 万行输出，终端会被刷爆。
        只打印前几条足够定位问题，同时 bad 仍然在累计真实总数。
        这也是写 profiler / 调试代码的通用习惯。

    ⚠ 坑 4：h_c[i] 和 ref[i] 的顺序别搞反。
        h_c = GPU 结果，ref = CPU 结果。
        虽然这里是加法（顺序反了也看不出），但查问题时打印反了会很误导。

  ────────────────────────────────────────────────────────────────
  【第 101 行】打印验证结论
  ────────────────────────────────────────────────────────────────
      printf("verify: %s (%d mismatches)\n", bad ? "FAIL" : "PASS", bad);

    · bad ? "FAIL" : "PASS" → 三目运算符：
          bad 非 0（有错）  → 打印 FAIL
          bad 为 0（全对）  → 打印 PASS
    · %s 用来打印字符串，%d 用来打印 bad 的数值。
    · 为什么这一行最重要：
      每次实验都必须先看这一行 —— 结果不对，后面的性能数字全都没有意义
      （跑得快，但算错了，那是无效优化）。

  ────────────────────────────────────────────────────────────────
  【第 104 行】double gb = 3.0 * bytes / 1e9;
  ────────────────────────────────────────────────────────────────
  这是整个程序的「性能理论核心」，一行决定带宽算得对不对。

    · 为什么乘 3？
          kernel 做的是 c[i] = a[i] + b[i]，每个元素要：
              读 a[i]  → 1 份数据
              读 b[i]  → 1 份数据
              写 c[i]  → 1 份数据
          合计搬运「3 份」。
          漏掉任何一项，带宽都会算错（少算 1/3 或 1/2）。

    · 为什么是 3.0（浮点）而不是 3？
        3.0 * bytes 会强制按浮点算，避免中间结果被当整数截断。

    · 为什么除以 1e9？
        把「字节」换算成「GB」。
        ⚠ 这里的 GB 是十进制（10^9），不是 GiB（1024^3）；
          显卡规格书上的带宽也是按 10^9 算的，所以必须一致，否则没法对比。

    · 本例数值：bytes = 268,435,456
        gb = 3.0 × 268,435,456 / 1e9 = 805.3 MB / 1e9 ≈ 0.8053 GB

  ────────────────────────────────────────────────────────────────
  【第 105 行】double bw = gb / (best_ms / 1e3);
  ────────────────────────────────────────────────────────────────
    · 带宽 = 总流量 ÷ 时间（单位：GB/s）。
    · best_ms / 1e3 把「毫秒」换算成「秒」，否则单位对不上。
    · 为什么也要用 double：
        带宽数值会到 1e11 量级（字节/秒），float 只有约 7 位有效数字，
        精度不够。涉及物理量计算的中间结果一律用 double。

    · 用刚才的真实数字走一遍：
        实测 best_ms = 3.29 ms
        → bw = 0.8053 / (3.29 / 1e3) = 0.8053 / 0.00329 ≈ 245 GB/s

  ────────────────────────────────────────────────────────────────
  【第 106～107 行】打印耗时与带宽
  ────────────────────────────────────────────────────────────────
      怎么判断这个数字是好还是坏：

        与显卡的理论峰值带宽（RTX 4060 Laptop ≈ 256.3 GB/s）相除，
        得到「峰值占比」：
              85% 以上  → 健康，说明已经很接近硬上限
              本程序实测 96%（block = 1024）→ 已经贴着天花板了

      ⚠ 重要观念：DRAM 跑到 100% 并不是目标，
        「用最少的时间算完」才是目标。
        带宽高只是「没有浪费」的证据，不是终点。

  ── 本部分小结 ──
      验证：容差比较 + 只打印前几条 + 先看 PASS/FAIL
      性能：流量 = 3 份数据；带宽 = 流量 ÷ 时间；离峰值越近越好

