第 1 章　GPU / CUDA 概念（11 条）
========================================================================

------------------------------------------------------------------------
1.1 CPU 和 GPU 的分工
------------------------------------------------------------------------
    CPU：核心少（几个到几十个），但每个核心很强，擅长复杂逻辑、if / else。
    GPU：核心极多（几千个），但每个核心很简单，擅长「同一件事重复几千遍」。

    类比：
      CPU = 一辆重型卡车（能拉复杂货物，单趟快）
      GPU = 一支一万辆车的快递车队（每辆很小，但总量碾压）

      搬一件复杂家具 → 卡车更快
      送一万个相同的小包裹 → 车队碾压

    深度学习里的矩阵运算，就是「一万个小包裹」，所以要用 GPU。

------------------------------------------------------------------------
1.2 host（主机）与 device（设备）
------------------------------------------------------------------------
    host   = CPU 那一侧（连同主机内存）
    device = GPU 那一侧（连同显存）

    代码里的命名习惯：
      带 h_ 前缀的在 host 侧（h_a、h_b、h_c、ref）
      带 d_ 前缀的在 device 侧（d_a、d_b、d_c）
    一眼就能看出这个数据住在哪边。

------------------------------------------------------------------------
1.3 主机内存和显存是两块分开的存储
------------------------------------------------------------------------
    这是 CUDA 最反直觉的一点：

      GPU 不能直接读你用 malloc 出来的 h_a！

    所以必须先「搬」过去：
      cudaMemcpy 把数据从主机内存拷到显存，GPU 才能算；
      算完还要再「搬」回来。

    代码里因此出现两次拷贝：
      cudaMemcpyHostToDevice   算之前，搬进去
      cudaMemcpyDeviceToHost   算之后，搬回来

------------------------------------------------------------------------
1.4 线程、block、grid：GPU 的「工人编号系统」
------------------------------------------------------------------------
    GPU 上干活的最小单位是「线程（thread）」。
    为了管理成千上万个线程，CUDA 把它们分成三层：

      grid（网格）       一次任务的全部线程
        └ block（线程块） 把线程分成一组一组
            └ thread（线程）真正干活的工人

    每个线程怎么知道「我是谁、我该算哪个元素」？
    靠四个内置变量：

      threadIdx.x   我在本 block 里排第几号
      blockIdx.x    我在第几个 block 里
      blockDim.x    一个 block 里有几个线程
      gridDim.x     一共有几个 block

    于是这一行：
        int idx = blockIdx.x * blockDim.x + threadIdx.x;
    就是在做「把我的三层编号换算成一个全局编号」，
    也就是「我负责处理第几个元素」。

    ⚠ 编号从 0 开始，不是从 1 开始。

------------------------------------------------------------------------
1.5 warp 和 SM：会在报告里反复出现的两个词
------------------------------------------------------------------------
    warp（线程束）：硬件真正调度的单位，固定 32 个线程。
      所以 block 大小最好是 32 的倍数（128 / 256 / 512 / 1024）。

    SM（流多处理器）：GPU 里的"小 CPU 核"，你的 4060 有 24 个。
      一个 block 会被分配到某个 SM 上执行。

    写代码时你暂时不用管它们，但读 profiler 报告时会一直看到。

------------------------------------------------------------------------
1.6 kernel 和 __global__
------------------------------------------------------------------------
    kernel = 「在 GPU 上并行执行的函数」。

    用 __global__ 关键字声明，例如：
        __global__ void vectorADD(...) { ... }

    这个关键字包含两层含义：
      ① 它在 GPU 上执行；
      ② 它只能由 CPU（主机端代码）来启动。

------------------------------------------------------------------------
1.7 <<<grid, block>>> 怎么读
------------------------------------------------------------------------
    启动 kernel 的写法：
        vectorADD<<<grid, block>>>(d_a, d_b, d_c, n);

    拆成两部分看就清楚了：
      函数名 + 参数      vectorADD(d_a, ...)   ← 和普通函数一样
      尖括号里的配置      <<<grid, block>>>     ← CUDA 独有语法

    尖括号里：
      第一个数 grid  = 要开多少个 block
      第二个数 block = 每个 block 里有多少个线程

    所以总线程数 = grid × block。
    本例 = 262144 × 256 = 67,108,864，正好等于 N。

------------------------------------------------------------------------
1.8 异步执行：CPU 发完命令就自己跑了
------------------------------------------------------------------------
    普通函数调用（在 CPU 上）是这样的：
        调用 → 等它算完 → 拿到返回值 → 再往下走

    kernel 启动不是这样的：
        启动 → CPU 立刻继续往下执行（GPU 在后台慢慢算）

    这个性质叫「异步（asynchronous）」。

    ⚠ 它会带来两个后果，非常关键：
      ① 不能用 CPU 的计时函数给 kernel 计时（你会测到几乎 0）；
      ② 想知道「算完了没有」，必须显式地等：
           cudaDeviceSynchronize()   等 GPU 全部干完
           cudaEventSynchronize(e)   等某个时间点到达

------------------------------------------------------------------------
1.9 cudaEvent：在 GPU 的时间线上打点
------------------------------------------------------------------------
    GPU 有自己的时间线。你可以在上面打两个时间戳：

      打 start → 启动 kernel → 打 stop → 等 stop 到达 → 读两点之间的毫秒数

    这就是三个函数的分工：
      cudaEventRecord      打点
      cudaEventSynchronize 等这个点真正到达
      cudaEventElapsedTime 算出两点之间过了多少毫秒

------------------------------------------------------------------------
1.10 这个程序到底在测什么？——带宽
------------------------------------------------------------------------
    kernel 干的事极其简单：读 a[i]、读 b[i]、写 c[i]，做一次加法。
    所以每处理 1 个元素，数据要在显存和芯片之间搬 12 个字节。

    「带宽（bandwidth）」= 单位时间能搬多少字节，单位 GB/s。

        带宽 = 总共搬了多少字节 ÷ 用了多少秒

    所以代码里写：gb = 3.0 * bytes / 1e9
      为什么乘 3？因为一共搬了三份：读 a、读 b、写 c。

    怎么判断这个数字好不好？
      拿它除以这块显卡的峰值带宽（约 256 GB/s），得到「峰值占比」。
      85% 以上算健康。本程序实测 96%，已经贴着天花板了。

------------------------------------------------------------------------
1.11 为什么要测 20 次，而且只取最小值？
------------------------------------------------------------------------
    笔记本 GPU 会因为温度升高而自动降频（thermal throttling）。
