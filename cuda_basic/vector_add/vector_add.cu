专题 7　为什么不能直接读 d_c？（CPU / GPU 内存空间的分界线）
------------------------------------------------------------------------

  ⚠ 先说明：本专题与上面的 CUDA_CHECK 宏无关，纯粹是因为读到这里时
    一定会冒出一个疑问，所以借着「专题」的编号把它一并讲透：

      疑问：「既然 h_c 和 d_c 装的都是结果，
             为什么不直接拿 h_c[i] 和 d_c[i] 比较？
             为什么非要先 cudaMemcpy 搬回来？」

------------------------------------------------------------------------
7.1 一句话答案：CPU 根本读不到 d_c
------------------------------------------------------------------------
    d_c 是「设备指针（device pointer）」，它指向的内存在 GPU 那一侧。
    你在 main 里（host 代码）写 d_c[i]，
    就像拿别人家的门禁卡去开自己家的门 ——
    地址是有的，但你的 CPU 既没权限、也没通路去访问那块内存。

    回顾零基础版 1.3 那个概念：两块存储是物理上分开的。

        主机内存 (h_*)                    显存 (d_*)
        ┌──────────────┐                 ┌──────────────┐
        │ h_a  h_b     │                 │ d_a  d_b     │
        │ h_c  ref     │                 │ d_c          │
        └──────────────┘                 └──────────────┘
             ↑                                 ↑
          CPU 能直接读写                  只有 GPU 能直接读写
             └──────── PCIe 总线 ─────────────┘
                  （唯一的通路，要「搬」才过得去）

      · h_c 是 CPU 地址空间里的地址  →  h_c[i] 合法；
      · d_c 是 GPU 地址空间里的地址  →  d_c[i] 非法。

------------------------------------------------------------------------
7.2 最坑的一点：编译器不会拦你
------------------------------------------------------------------------
        float* d_c;              // 类型就是 float*
        float  x = d_c[0];       // 类型上完全合法，编译通过

    因为 d_c 和 h_c 的类型一模一样（都是 float*），
    编译器区分不了它们。所以这个错误编译期完全不报，
    要执行到那一行才炸：

        Segmentation fault (core dumped)

    （或者 dmesg / 内核日志里出现 Xid 错误。）

    ⚠ 这是 CUDA 最难查的一类 bug：
      代码看着没错，编译也没错，就是崩。

    历史背景（为什么现在更容易搞错）：
      早期的 CUDA 用完全独立的设备地址体系；
      现在（compute 2.0+ 的 64 位 UVA，统一虚拟寻址）
      所有指针共用一套地址空间，
      所以 d_c 打印出来像个正常地址，更容易让人误以为可以直接用。

------------------------------------------------------------------------
7.3 顺带纠正一个前提错误：那一刻 h_c 里还是垃圾
------------------------------------------------------------------------
    就算撇开权限问题不谈，「直接比较 h_c 和 d_c」这个想法本身
    还藏着一个前提错误：

        float* h_c = (float*)malloc(bytes);   // 第 49 行：只申请，没初始化
        ...
        // 第 89 行之前，h_c 里全是随机值（垃圾数据）
        CUDA_CHECK(cudaMemcpy(h_c, d_c, bytes, cudaMemcpyDeviceToHost));
        // 第 89 行之后，h_c 才真的有内容

    malloc 只给你一块内存，不会清零。
    所以第 89 行那次 memcpy 不只是「搬数据」，
    它同时是「给 h_c 赋值」的唯一途径。

------------------------------------------------------------------------
