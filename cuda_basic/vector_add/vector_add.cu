7.6 那为什么这个示例程序还是选择 memcpy？
------------------------------------------------------------------------

        理由              说明
        ---------------   ----------------------------------------------
        教学清楚          搬运被「显式」写出来，你看得见它存在
        代码最短          一行 memcpy + 一个 for 循环，零基础也能看懂
        这个规模无所谓    搬运耗时只影响「验证」，不影响性能结论
        和 profiler 配合  ncu 只测 kernel（3.40 ms），搬运被干净隔离在外

------------------------------------------------------------------------
7.7 顺便算一下：时间都花在哪（N = 2^26，PCIe 按 12 GB/s 估）
------------------------------------------------------------------------

        阶段                        数据量            估时
        -------------------------   --------------    ------------
        kernel 本体                 805 MB @ 245.8    ** 3.28 ms **
        上行拷贝 ×2（a、b）        512 MiB           ~45 ms
        下行拷贝 ×1（c）            256 MiB           ~22 ms
        CPU 参考实现                67M 次加法        ~几十 ms
        合计                                          ~100 ms 量级

    看到重点了吗：kernel 只占整个程序的 3% 左右。

    这正是 AI-Infra 的核心命题之一。
    真实推理场景里，如果一个算子很快、但来回搬运数据很慢，
    用户感受到的就是慢。
    所以优化时永远要多问一句：
        这块数据现在在哪？我有没有必要让它跑这一趟？
    后面做 kernel 融合（fusion）的根本动机就在这里。

