  【第 68 行】CUDA_CHECK(cudaGetLastError());
  ────────────────────────────────────────────────────────────────
    · kernel 启动失败时「不会」通过返回值报错（启动语句本身没有返回值），
      必须用 cudaGetLastError() 主动去查「上一次 CUDA 调用有没有报错」。
    · 常见失败原因：block 超过 1024、grid 维度超过上限等。
    · 不加这一行的后果：kernel 静默不执行，
      后面测出来「快得离谱」或「结果全 0」，而你不知道为什么。

  ────────────────────────────────────────────────────────────────
  【第 69 行】CUDA_CHECK(cudaDeviceSynchronize());
  ────────────────────────────────────────────────────────────────
    · 等 GPU 把队列里的活全干完（会阻塞 CPU，直到空闲）。
    · warm-up 为什么要同步？
        ① 确保第一次运行「真正完成」，让 GPU 把频率提上去；
           （GPU 空闲时会降频，一上来就跑计时会偏慢）
        ② 让指令缓存、L2 缓存被「预热」；
        ③ 把「第一次启动的额外开销」挡在正式计时之外。

  ── 为什么需要 warm-up（高频面试点）──
      第一次运行时 GPU 处于低频状态、指令缓存是冷的，
      测出来的时间会明显偏大，甚至差 10% 以上。
      先跑一遍热身，再开始正式测量。
      实测教训：同一份代码同一组参数，
        第一次跑 4.038 ms，第二次 3.529 ms —— 13% 的差距纯粹来自温度 / 频率。

  ────────────────────────────────────────────────────────────────
  【第 72～74 行】创建「计时事件」
  ────────────────────────────────────────────────────────────────
      cudaEvent_t start, stop;
      CUDA_CHECK(cudaEventCreate(&start));
      CUDA_CHECK(cudaEventCreate(&stop));

    · cudaEvent_t 是 CUDA 的「事件（event）」类型，
      用来在 GPU 的时间线上打一个「时间戳」。
    · 为什么不直接用 CPU 时钟？
      因为 kernel 是异步的，CPU 侧的计时包不住 GPU 的实际执行时间。
      用 GPU 的事件，量到的才是 GPU 真正干活的时间。
    · 同样要传地址（&start），理由与 cudaMalloc 完全相同：
      cudaEventCreate 需要「修改 start 这个变量本身」。

  ────────────────────────────────────────────────────────────────
  【第 76 行】const int iters = 20;
  ────────────────────────────────────────────────────────────────
    · 重复测 20 次，用来做统计（取最好成绩）。
    · const 表示「这个变量之后不再修改」，是给编译器也是给读者的承诺。

  ────────────────────────────────────────────────────────────────
  【第 77 行】float best_ms = 1e30f;
  ────────────────────────────────────────────────────────────────
    · 1e30f = 10 的 30 次方，一个「极大的数」当初值，
      保证第一次比较时必定被真实结果替换掉。
      （这是「求最小值」的标准起手式）
    · 为什么取最小值，而不是平均值或中位数？
        GPU 会因为温度升高而降频（thermal throttling），
        时间只会被「拖慢」，不会凭空变快。
        所以所有测量里「最快的那一次」最接近这台机器真正能跑到的上限。
        用平均值反而会把降频的污染混进来。

  ────────────────────────────────────────────────────────────────
  【第 79 行】CUDA_CHECK(cudaEventRecord(start));
  ────────────────────────────────────────────────────────────────
    · 在当前 GPU 时间线上打一个「开始」时间戳。
    · 注意 Record 本身也是异步的：
      它记录的是「GPU 执行到这一个命令的时刻」，不是 CPU 此刻的时刻。

  ────────────────────────────────────────────────────────────────
  【第 80 行】vectorADD<<<grid, block>>>(d_a, d_b, d_c, n);
  ────────────────────────────────────────────────────────────────
    · 被测对象：这里只测 kernel 本身。
    · 为什么不计 cudaMemcpy？
      数据搬运属于「传输」，不是 kernel 性能；
      混在一起会掩盖 kernel 的真实速度，也让不同实现之间无法公平比较。
    · 为什么把启动语句夹在两个 Record 之间？
      这样 start 和 stop 之间「只有」kernel 执行这一段。

  ────────────────────────────────────────────────────────────────
  【第 81 行】CUDA_CHECK(cudaEventRecord(stop));
  ────────────────────────────────────────────────────────────────
    · 打一个「结束」时间戳。它被排在 kernel 之后，
      所以它对应的时刻 = kernel 真正跑完的时刻。

  ────────────────────────────────────────────────────────────────
  【第 82 行】CUDA_CHECK(cudaEventSynchronize(stop));
  ────────────────────────────────────────────────────────────────
    · 等 stop 事件真正到达（也就是 kernel 真的跑完了），会阻塞 CPU。
    · 这一步必须有：否则时间还没记录完就去读，
      会读到 0 或者上一次的旧值。
      （这是刚学 CUDA 计时最常见的 bug）

  ────────────────────────────────────────────────────────────────
  【第 84～85 行】CUDA_CHECK(cudaEventElapsedTime(&ms, start, stop));
  ────────────────────────────────────────────────────────────────
    · 计算 start 与 stop 两个事件之间相隔多少毫秒，写进 ms。
    · 参数顺序：先目标 &ms，再 start，再 stop（别搞反）。
    · 为什么也要传 &ms？同样因为函数要「修改 ms 这个变量」。
    · 精度约 0.5 微秒，对毫秒级的 kernel 完全够用。

  ────────────────────────────────────────────────────────────────
  【第 86 行】if (ms < best_ms) best_ms = ms;
  ────────────────────────────────────────────────────────────────
    · 只保留最快的那一次，理由见第 77 行。
    · 注意别写成 ms > best_ms —— 那就变成「取最慢」了。

  ── 计时四步口诀（背下来）──
      create → record(start) → 跑东西 → record(stop)
             → synchronize(stop) → elapsedTime → destroy
      对应代码第 72～74 行 → 79 行 → 80 行 → 81 行 → 82 行 → 84 行 → 115 行。

