第七部分：收尾（第 109～118 行）
========================================================================

  ────────────────────────────────────────────────────────────────
  【第 110 行】释放主机内存
  ────────────────────────────────────────────────────────────────
      free(h_a); free(h_b); free(h_c); free(ref);

    · malloc 与 free 必须「成对出现」，一共分配了 4 块，就释放 4 块。
    · 不释放会怎样：内存泄漏（memory leak）。
      程序短命时操作系统会替你回收，看不出问题；
      但长驻进程（服务器、训练框架）里就是实打实的「内存只增不减」。
    · 顺序无所谓，但「有几块就释放几块」绝不能漏。
      对照检查：malloc 出现 4 次 → free 也必须出现 4 次。

  ────────────────────────────────────────────────────────────────
  【第 111～113 行】释放显存
  ────────────────────────────────────────────────────────────────
      CUDA_CHECK(cudaFree(d_a));   // 同理 d_b、d_c

    · cudaMalloc 与 cudaFree 必须成对，这里是 3 对。
    · 显存泄漏的代价比内存泄漏更大：
        本机只有 8 GB 显存，一个 256 MiB 的数组泄漏，
        跑几十次循环就「out of memory」了，
        而且报错往往发生在一个看起来毫不相干的 cudaMalloc 上，很难查。
    · 为什么这里也包 CUDA_CHECK：
        释放失败（例如指针已被释放过 → double free）也能当场发现。
    · 对于 cudaFree，传的是 d_a 本身（不是 &d_a）——
      因为它是「按地址释放」，不需要函数回写这个变量。

  ────────────────────────────────────────────────────────────────
  【第 114～115 行】销毁事件对象
  ────────────────────────────────────────────────────────────────
      CUDA_CHECK(cudaEventDestroy(start));
      CUDA_CHECK(cudaEventDestroy(stop));

    · cudaEventCreate 与 cudaEventDestroy 必须成对，这里是 2 对。
    · 事件对象本身占的资源很少，但既然是「创建/销毁」型 API，
      就一律遵守配对原则，养成习惯，不要靠「反正没多少」来偷懒。
    · 为什么传 start 而不是 &start：和 cudaFree 同理，只是销毁，不用回写。

  ────────────────────────────────────────────────────────────────
  【第 116 行】return 0;
  ────────────────────────────────────────────────────────────────
    · 返回 0 表示「正常结束」——这是操作系统的约定：0 表示成功，非 0 表示失败。
    · 这个返回值可以被 shell 读到：
          ./build/bin/vector_add && echo "上一条命令成功了"
      （&& 只在退出码为 0 时才执行后面那句）
      CI / 自动化脚本就是靠这个判断实验有没有跑通。
    · 养成习惯：验证失败时其实更应该 return 1，
      这样脚本能自动发现「跑完了但结果是错的」。
      本程序没这么做，属于可改进点（见后面「可以改进的地方」）。

  ── 三条「配对原则」速记（内存管理的总纲）──
      malloc        ↔ free              （主机内存）
      cudaMalloc    ↔ cudaFree          （显存）
      cudaEventCreate ↔ cudaEventDestroy（事件）
    写任何新 kernel 时，先把这三组的「创建」写好，再立刻把「销毁」补齐，
    最后才往中间填内容 —— 这样永远不会漏。

