专题 6　两个常见疑问
------------------------------------------------------------------------
   问：为什么不直接写成一个函数？
   答：三个原因。
       ① 行号问题：函数里的 __LINE__ 只能拿到函数内部的行号，
          拿不到「调用处」的行号。宏是文本替换，所以可以。
       ② 参数问题：宏的参数可以是任意代码片段（比如整个 cudaMalloc(...)），
          函数的参数做不到这一点。
       ③ 附带好处：宏没有函数调用的开销。

   问：为什么宏定义里最后一个 } 后面不写分号？
   答：因为分号由调用处提供。
      你写的 CUDA_CHECK(...); 那个分号会落在 while(0) 后面，
      展开成 while(0); —— 这才是完整语句。
      如果宏里自己又写了一个分号，展开后就会多出一个空语句，
      在 if / else 里反而会出问题。

