------------------------------------------------------------------------
7.5 那有没有办法不搬？有三条路
------------------------------------------------------------------------

  ── 路线 A：统一内存（Unified Memory / managed memory）──

        float* c;
        cudaMallocManaged(&c, bytes);   // 不区分 host / device，一套指针两边都能用
        vectorADD<<<grid, block>>>(...);
        cudaDeviceSynchronize();
        printf("%f\n", c[0]);          // 合法！CPU 直接就能读

    看起来完美，但注意：数据该搬还是得搬，只是 CUDA 替你搬了。

    原理是「按需缺页（page fault）」：
      CPU 一碰这块内存，驱动发现它现在在显存里，就把它迁到主机内存。
      对 256 MiB 这种规模，迁移是成块进行的，
      所以实际耗时和显式 memcpy 差不多 —— 只是你看不见了。

    这就是为什么「可改进点」里写「学习阶段不建议」：
      它会让你看不见数据传输的真实成本。
      而做推理框架时，这个成本往往就是瓶颈。

  ── 路线 B：零拷贝 / 映射锁页内存（zero-copy, mapped pinned memory）──

        float* h_c;  cudaHostAlloc(&h_c, bytes, cudaHostAllocMapped);
        float* d_c;  cudaHostGetDevicePointer(&d_c, h_c, 0);  // d_c 指向主机内存
        // GPU 直接把结果写进主机内存，CPU 立刻就能读，不需要 memcpy

    原理：让 GPU 通过 PCIe 直接写主机内存。
    CPU 确实能直接读了，但这非常慢：

        通路                            带宽          与显存之比
        ----------------------------    -----------   ----------
        显存带宽                        ~256 GB/s     100%
        PCIe 4.0 ×8 双向理论值          ~16 GB/s      ~6%
        PCIe 实测可用                   ~12 GB/s      ~5%

    （笔记本 RTX 4060 一般是 PCIe 4.0 ×8；
      你测到的 245.8 GB/s 就是第一行那个数量级。）

    而且零拷贝下 GPU 每一次访存都要跨总线，
    延迟在 1 微秒量级，访问模式还得合并，否则性能会崩。

  ── 路线 C：把对拍也放到 GPU 上做（实践中最常用的方案）──

        __global__ void compareKernel(const float* gpu, const float* ref,
                                      int n, int* bad) {   // 只拷回一个计数器！
            int idx = blockIdx.x * blockDim.x + threadIdx.x;
            for (int i = idx; i < n; i += blockDim.x * gridDim.x) {
                if (fabsf(gpu[i] - ref[i]) > 1e-5f) {
                    atomicAdd(bad, 1);
                }
            }
        }

    流程变成：
      ① CPU 算 ref（这一步不能省，见下）；
      ② 把 ref 拷到显存（256 MiB 上行）；
      ③ GPU 上对拍，67M 个元素的比较分摊到几万个线程；
      ④ 只把 bad 这个 int（4 字节）拷回来。

    省下了「拷回 256 MiB 的 h_c」这一趟（约 22 ms），
    而且对拍本身从串行变成并行。代价是上行多拷了 256 MiB。
    净收益要具体算，但思路是：让数据留在离算力近的地方。

    ⚠ 但有一步绝不能偷懒：
      不要为了方便把 ref 也在 GPU 上算出来。
      参考实现的价值在于「独立的第二意见」——
      用完全不同的代码、不同的执行方式得到同一个结果。
      如果两边都是 GPU kernel 而且逻辑相通，
      那就是「自己证明自己对」，
      一个共同的理解错误会被同时复制到两边，对拍就失去意义了。

