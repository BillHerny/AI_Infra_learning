    要「灌满」显存带宽，数据量就必须足够大；
    数据太小的话 kernel 还没热身就结束了，测出来的数字没有意义。

  ────────────────────────────────────────────────────────────────
  【第 41 行】int block = (argc > 2) ? atoi(argv[2]) : 256;
  ────────────────────────────────────────────────────────────────
  结构与第 40 行完全一样，只是换成第 2 个参数，默认值改成 256。

    · block 是「每个 block 里有多少个线程」。
    · 注意：block 最好是 32（一个 warp 的大小）的整数倍才高效，
      并且不能超过 1024（硬件上限）。代码里没有做校验，属于可改进点。

