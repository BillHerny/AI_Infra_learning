------------------------------------------------------------------------
0.1 程序是怎么从这一份 .cu 文件变成能跑的东西的
------------------------------------------------------------------------
    你写的文字（源代码） → 编译器（这里是 nvcc） → 可执行文件 → 运行

    你敲的三条命令正好对应这个流程：
      cmake -S . -B build      生成"施工图"（Makefile）
      cmake --build build      按图施工，生成 build/bin/vector_add
      ./build/bin/vector_add   把成品跑起来

    ⚠ 要分清两种错误：
      编译期错误：代码语法/类型不对，根本生不成可执行文件；
      运行期错误：能编译，但跑起来结果不对或崩溃。
      之前那个「宏丢了反斜杠」就是编译期错误。

------------------------------------------------------------------------
0.2 变量与类型：不同大小的"盒子"
------------------------------------------------------------------------
    int      x = 5;        整数盒子
    float    f = 1.0f;     小盒子，装小数，约 7 位有效数字
    double   d = 1.0;      大盒子，装小数，约 15 位有效数字
    size_t   n = 100;      专门用来装「大小 / 个数」的无符号整数
    char     c = 'A';      装一个字符
    float*   p;            注意这里有星号，它是「指针」，见 0.3

    为什么要有这么多类型？
      内存里所有东西都只是 0 和 1。
      类型的作用是告诉编译器：从某个地址开始，取几个字节？按什么规则解释？

------------------------------------------------------------------------
0.3 指针是什么？
------------------------------------------------------------------------
    把内存想成一排房间。每个房间有门牌号（地址），房间里放着东西。

      普通变量装的是「东西」；
      指针装的是「门牌号」。

        int  x = 5;     某个房间里放着 5
        int* p = &x;    p 这个房间里放的是"x 那个房间的门牌号"

    所以 float* a 的意思是：a 里装的是「某个 float 房间的地址」。

------------------------------------------------------------------------
0.4 & 和 * 这两个符号
------------------------------------------------------------------------
    &x   → 取得 x 的地址（门牌号）          读作「address of x」
    *p   → 顺着 p 里的门牌号去那个房间取东西   读作「解引用」

        int  x = 5;
        int* p = &x;    // p 拿到 x 的门牌号
        *p = 7;         // 去 p 指向的房间，把 5 改成 7
                        // 因为改的就是 x 那个房间，所以 x 也变成 7 了

    ⚠ 同一个星号 * 在两个位置意思不同：
      写在「声明」里（float* p）→ 表示「p 是一个指针」；
      写在「表达式」里（*p = 7）→ 表示「去那个地址取值」。

------------------------------------------------------------------------
0.5 数组其实就是「连续的一排房间」
------------------------------------------------------------------------
        float* h_a = (float*)malloc(100);   // 申请了 100 字节
        h_a[0] 是第一间，h_a[1] 是第二间
        （每间占 4 字节，因为一个 float 是 4 字节）

    h_a[i] 这种写法，编译器会自动把它理解成 *(h_a + i)：
      「从 h_a 这个地址往后走 i 个 float，然后去那个房间取值」。

    所以「数组」和「指针」在 C 语言里几乎是一回事。

------------------------------------------------------------------------
0.6 const：一个「我只读、不写」的承诺
------------------------------------------------------------------------
        const float* a

    意思是：我承诺不会通过 a 去修改它指向的内容。
      好处一：防止你手滑写错（编译器会拦住你）；
      好处二：编译器知道这块内存只读，可以更大胆地优化。

    读法小技巧：从右往左读
      const float* a  →  a 是一个指针，指向 const float

------------------------------------------------------------------------
0.7 (float*) 这种写法是什么？
------------------------------------------------------------------------
    它叫「强制类型转换（cast）」。

    malloc 返回的是 void*，意思是「一块内存的地址，但我不知道里面装什么」。
    我们清楚里面要装 float，所以写 (float*) 告诉编译器：请按 float 来用。

------------------------------------------------------------------------
0.8 函数、参数、返回值、void
------------------------------------------------------------------------
    函数 = 一段可以反复使用的代码。
      参数：写在函数名后面的括号里，是"传进去"的东西；
      返回值：函数算完之后"交出来"的东西。

    void 表示「没有」：
        void vectorADD(...)   → 这个函数不返回任何值

    所以结果没法靠返回值送出来，只能通过「指针参数」写进那块内存。
    这就是为什么 kernel 的参数里有 float* c —— 它是"输出通道"。

------------------------------------------------------------------------
0.9 命令行参数 argc / argv
------------------------------------------------------------------------
    你这样运行：./build/bin/vector_add 67108864 512

    程序内部会收到：
      argc    = 3                     （一共 3 个"词"：程序名 + 2 个参数）
      argv[0] = "./build/bin/vector_add"
      argv[1] = "67108864"
      argv[2] = "512"

    ⚠ argv 里装的全是「字符串」，想当数字用必须先转换，
      这就是 atoi（ASCII to integer）的作用。

------------------------------------------------------------------------
0.10 #include 和 #define：预处理
------------------------------------------------------------------------
    在真正编译之前，有一个「预处理」步骤，它只做文本层面的处理。

    #include <cstdio>
      → 相当于把 cstdio 这个文件的内容"抄"到这一行。
        抄进来的是别人的函数声明，这样你才能用 printf。

    #define CUDA_CHECK(call) ...
      → 定义「宏（macro）」：本质是纯文本替换。
        你写 CUDA_CHECK(cudaMalloc(...));
        编译器会把它整段替换成宏体里那些代码。

    ⚠ 宏最大的坑：
      默认情况下，一个 #define 只管一行。
      要把多行都算进宏体，必须在每一行的末尾加一个反斜杠，这叫「续行符」。
      而且这个反斜杠必须是该行的最后一个字符，后面连一个空格都不能有！
      一旦断掉，宏体就残缺，报出来的错会跟你真正的问题毫无关系
      （你们之前就踩过这个坑：报了一堆"expected a declaration"）。

------------------------------------------------------------------------
0.11 printf 的格式符：占位符
------------------------------------------------------------------------
    printf("N = %d, array = %.1f MiB\n", n, m);

      %d    → 这里放一个整数
      %s    → 这里放一个字符串
      %f    → 这里放一个小数（float / double）
      %.1f  → 小数，只保留 1 位
      %p    → 这里放一个地址（指针）
      \n    → 换行符（相当于敲回车）

    ⚠ 格式符和后面的参数必须一一对应、类型匹配，否则会打印出乱码。

------------------------------------------------------------------------
0.12 ? : 三目运算符
------------------------------------------------------------------------
    写法：条件 ? 条件成立时的值 : 条件不成立时的值

    例子：int n = (argc > 1) ? atoi(argv[1]) : (1 << 26);

    读法：如果命令行给了参数，就用这个参数；否则用默认值 1 << 26。

------------------------------------------------------------------------
0.13 1 << 26 是什么？
------------------------------------------------------------------------
    << 是「左移」：把二进制整体往左挪若干位。
    1 左移 26 位 = 2 的 26 次方 = 67,108,864。

    那为什么不直接写 67108864？
      ① 一眼能看出「这是 2 的幂」；
      ② 不容易数错 0 的个数。

    同理：1 << 20 就是 1 MiB（2 的 20 次方个字节）。

------------------------------------------------------------------------
0.14 do { ... } while(0) 是什么鬼？
------------------------------------------------------------------------
    它先执行一遍循环体，再看条件；而条件被写死成 0（假），
    所以永远只执行一次 —— 它的唯一作用就是
    「把好几行语句打包成一条语句」。

    为什么需要打包？因为宏是文本替换：
      如果不用它，当你写 if (x) CUDA_CHECK(...); else ... 时，
      宏体里的多行代码会把 if / else 的结构撑破，导致编译错误。
    用 do { } while(0) 包起来，宏在任何地方展开都安全。

------------------------------------------------------------------------
0.15 sizeof：某个类型占几个字节
------------------------------------------------------------------------
        sizeof(float)  = 4
        sizeof(int)    = 4
        sizeof(double) = 8

    所以 bytes = n * sizeof(float) 的意思就是
      「n 个 float 一共占多少字节」。

------------------------------------------------------------------------
0.16 两个新手最容易踩的数值坑
------------------------------------------------------------------------
    坑一：整数除法会丢掉小数
        5 / 2 = 2（不是 2.5）
        所以换算 MiB 时要写 1024.0 而不是 1024，否则小数全被丢掉。

    坑二：int 会溢出
        int 最大约 21 亿。
        n = 2^26（6700 万）时 n * 4 还安全；
        但 n 再大下去，n * 4 就会溢出成负数，程序行为完全错乱。
        所以代码里写成 (size_t)n * sizeof(float)：
        先把 n 转成大整数，再乘，就不会溢出。

