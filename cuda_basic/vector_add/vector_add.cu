  ────────────────────────────────────────────────────────────────
  【第 34～35 行】最普通的单线程 C 代码
  ────────────────────────────────────────────────────────────────
      void vectorADD_CPU(const float* a, const float* b, float* c, int n){
          for(int i = 0; i < n; i++) c[i] = a[i] + b[i];}

    · 它与 kernel 的差别，一句话说完：
          没有 __global__、没有 <<< >>>、没有 idx；
          就靠一个 for 循环从 0 走到 n-1，老老实实一个一个算。

    · 参数与 kernel 完全一致（a、b、c、n），因为这样才能「同一套输入、
      两个实现、互相对照」。

    · 作用：当「标准答案」。
        用来验证 GPU 结果对不对，也就是「对拍（cross-check）」。

    · 为什么必须有它？
        没有基准，就没有正确性保证。
        GPU 写错了往往不是报错，而是「静默地算错」——
        只有对拍才能发现。

    · 代价：它是「串行」的：
        总工作量 = n 次循环，全在一个 CPU 核上排队做。
        N = 2^26 时比 GPU 慢几百倍，所以：
              只用于验证，绝不参与计时。
        （把 CPU 时间混进性能统计里，会得到一个毫无意义的数字）

  ── 为什么叫「参考实现（reference implementation）」──
      它不追求快，只追求「一看就懂、一看就信」。
      后续做 reduction、softmax、GEMM 时，你都要先写一份 CPU 版，
      再用它去对拍 GPU 版 —— 这是算子开发的标准工作流。
      ⚠ 反过来说：如果两边都错了（比如理解错了公式），
        对拍是发现不了的。所以「写对公式」要靠你自己把关。

